---@diagnostic disable: need-check-nil, param-type-mismatch, undefined-field
-- The invariants of the generated tables (ADR 0032): they equal what `gen-unicode` generates from the pinned inputs, every
-- file carries the Unicode License v3 notice, the version and the names of its sources, the pins are well formed, and the
-- version of the loader is the version of the URLs of both inputs (and of the conformance file of `hecate-unicode`).
local test = require("harness.test")
local data = require("hecate.unicode_data")
local ucd = require("lib.unicode_ucd")
local sha256 = require("lib.sha256")
local task = require("tasks.gen_unicode")
local T = test.Case("UnicodeDataInvariantsTest")

local here = (debug.getinfo(1, "S").source:match("^@(.*)[/\\][^/\\]*$") or "."):gsub("\\", "/")
local ROOT = here .. "/../../../.."
local OUT = ROOT .. "/packages/unicode-data/src/hecate/unicode_data"
local FILES = { "init.lua", "combining_class.lua", "decomposition.lua", "composition.lua" }

local function read(path)
  local file = io.open(path, "rb")
  if not file then return nil end
  local text = file:read("a")
  file:close()
  return text
end

local function pins()
  return assert(loadfile(here .. "/../external.lua"))()
end

local function committed(name) return assert(read(OUT .. "/" .. name), name) end

local function names_of(entries)
  local names = {}
  for index, entry in ipairs(entries) do names[index] = entry.name end
  return names
end

function T:test_the_pins_name_the_two_inputs_with_a_well_formed_sha256_and_one_unicode_version()
  local entries = pins()
  self:assert_equal(2, #entries)
  self:assert_equal("UnicodeData.txt,DerivedNormalizationProps.txt", table.concat(names_of(entries), ","))
  local seen = {}
  for _, entry in ipairs(entries) do
    self:assert_true(type(entry.sha256) == "string" and entry.sha256:find("^%x+$") ~= nil and #entry.sha256 == 64, entry.name .. ": sha256")
    self:assert_equal(entry.sha256:lower(), entry.sha256, entry.name .. ": lowercase hex")
    self:assert_false(seen[entry.sha256], "two inputs have the same digest")
    seen[entry.sha256] = true
    self:assert_equal("https://www.unicode.org/Public/" .. data.unicode_version .. "/ucd/" .. entry.name, entry.url, entry.name)
    self:assert_equal(data.unicode_version, ucd.version_of_url(entry.url), entry.name)
  end
end

function T:test_the_version_of_the_loader_is_the_version_of_both_inputs_and_of_the_conformance_file()
  for _, entry in ipairs(pins()) do self:assert_equal(data.unicode_version, ucd.version_of_url(entry.url), entry.name) end
  local conformance = assert(loadfile(here .. "/../../../unicode/tests/external.lua"))()
  self:assert_true(#conformance >= 1)
  for _, entry in ipairs(conformance) do
    self:assert_equal(data.unicode_version, ucd.version_of_url(entry.url), "hecate-unicode " .. entry.name .. " must test the version of the data")
  end
end

function T:test_every_committed_file_starts_with_the_notice_names_its_sources_and_carries_the_license()
  local entries = pins()
  local source = ("-- Source: Unicode Character Database %s, %s (https://www.unicode.org/Public/%s/ucd/)."):format(
    data.unicode_version, table.concat(names_of(entries), " and "), data.unicode_version)
  local license = {}
  for line in ucd.LICENSE:gmatch("([^\n]*)\n") do license[#license + 1] = line == "" and "--" or ("-- " .. line) end
  local expected_license = table.concat(license, "\n")
  for _, name in ipairs(FILES) do
    local text = committed(name)
    self:assert_true(text:find("^%-%- GENERATED by `lua tools/run.lua gen%-unicode`: do not edit by hand%.\n"), name .. ": first line")
    self:assert_true(text:find(source, 1, true) ~= nil, name .. ": version and source file names")
    self:assert_true(text:find("-- Layout `format` " .. data.format .. ".", 1, true) ~= nil, name .. ": layout")
    self:assert_true(text:find(expected_license, 1, true) ~= nil, name .. ": the whole Unicode License v3 notice")
    self:assert_true(text:find("UNICODE LICENSE V3", 1, true) ~= nil, name)
    self:assert_true(text:find("Copyright © 1991-", 1, true) ~= nil, name .. ": copyright line")
    -- The notice comes before the code: no module line above it.
    local license_at = text:find("UNICODE LICENSE V3", 1, true)
    local code_at = text:find("\nglobal ", 1, true)
    self:assert_true(license_at < code_at, name .. ": the notice precedes the code")
    -- And the header is comments only, up to the first blank line that follows the notice.
    for line in text:sub(1, code_at):gmatch("([^\n]*)\n") do
      self:assert_true(line == "" or line:find("^%-%-") ~= nil, name .. ": a line that is not a comment before the code: " .. line)
    end
  end
end

function T:test_the_committed_tables_are_exactly_what_the_renderer_makes_of_them()
  -- Offline: the model read back from the committed data, rendered again, gives the committed files byte for byte (the
  -- layout, the order, the header and the license cannot drift from the generator).
  local model = {
    combining = data.load("combining_class"),
    decomposition = data.load("decomposition"),
    composition = data.load("composition"),
  }
  local rendered = ucd.render(model, { version = data.unicode_version, files = names_of(pins()) })
  for _, name in ipairs(FILES) do
    self:assert_not_nil(rendered[name], name)
    self:assert_true(rendered[name] == committed(name), name .. " differs from what the generator renders")
  end
end

function T:test_the_committed_tables_equal_the_generated_ones_when_the_pinned_inputs_are_downloaded()
  local missing
  for _, entry in ipairs(pins()) do
    local text = read(ROOT .. "/.hecate/fixtures/unicode-data/" .. entry.name)
    if text == nil or sha256.hex(text) ~= entry.sha256 then missing = entry.name end
  end
  if missing then
    -- The job `gen-unicode --check` of CI downloads the inputs and runs the same comparison.
    io.stderr:write(("# skipped: %s is not downloaded (lua tools/run.lua fetch-fixtures unicode-data)\n"):format(missing))
    return
  end
  local report = task.run({ root = ROOT, args = { "--check" } })
  self:assert_true(report.ok, table.concat(report.problems, "; "))
  self:assert_equal(data.unicode_version, report.data.version)
  self:assert_equal(0, #(report.data.stale or {}))
end

return T
