-- The workflow templates of `hecate generate workflow` and `hecate new --ci github` (cli-and-packaging.md, "Generated
-- workflows"). `ci`, `contract` and `docs-pages` exist; `release` is still to do. A workflow calls only `hecate` commands, installs the executable with the setup
-- action of the project and pins every third-party action by commit SHA (the tag in a comment).
global <const> require, table, ipairs, type, error, tostring

local core = require("hecate.core")

---@class hecate.cli.templates.workflows
local M = {}

--- The setup action: `setup/` of the package `actions`, whose read-only mirror is `hecate-framework/hecate-actions`
--- (ADR 0017); the workflows write `<SETUP_ACTION>@<SETUP_REF>`.
M.SETUP_ACTION = "hecate-framework/hecate-actions/setup"

--- The tag of the setup action that the generated workflows use. PLACEHOLDER: the tags of Hecate and of the mirror of the
--- package `actions` have no `v` and follow the LuaRocks version form `<version>-<revision>` (owner, 2026-11-25); the release process
--- pins the real one (the tag of the release, then its commit SHA with the tag in a comment, cli-and-packaging.md) when it
--- tags the action; until the owner has created the mirror and the first release, no such tag exists.
M.SETUP_REF = "0.0.0-1"

--- The revision of a release of Hecate (`<version>-<revision>`, the LuaRocks version form of the tags and of the `version`
--- input of the setup action). Every release of Hecate is revision 1 until a release has to be re-issued with the same
--- version; the workflows name `<hecate_version>-<REVISION>`.
M.REVISION = 1

--- The checkout action, pinned by commit SHA (the same pin as the workflows of the monorepo).
M.CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7"

--- The cache action, pinned by commit SHA (the same pin as the workflows of the monorepo).
M.CACHE = "actions/cache@55cc8345863c7cc4c66a329aec7e433d2d1c52a9 # v6"

--- The kinds of workflow that exist.
M.kinds = { ci = true, contract = true, ["docs-pages"] = true }

--- The kinds of workflow of the specification that are still to do (`release` waits for the release process and the
--- installers, an owner gate).
M.planned_kinds = { "release" }

--- The Pages actions of the `docs-pages` workflow, pinned by commit SHA (the same pins as `.github/workflows/website.yml`
--- of the monorepo, which is where they were taken from; keep them in step).
M.CONFIGURE_PAGES = "actions/configure-pages@45bfe0192ca1faeb007ade9deae92b16b8254a0d # v6"
--- The artifact action of Pages, pinned by commit SHA.
M.UPLOAD_PAGES_ARTIFACT = "actions/upload-pages-artifact@fc324d3547104276b827a68afc52ff2a11cc49c9 # v5"
--- The deploy action of Pages, pinned by commit SHA.
M.DEPLOY_PAGES = "actions/deploy-pages@368f82528645a54fb793d4d04e342629a3f51346 # v5"

---@class hecate.cli.WorkflowParameters
---@field hecate_version string  the version of Hecate the project is generated with (the version the setup action installs)
---@field contract? boolean  the project has a `contract` section: export and lint the contract
---@field doc? boolean  build the documentation (`hecate doc build --yes`)

--- A YAML double-quoted scalar for the release of a version string, `<version>-<REVISION>` (no escapes needed for a SemVer,
--- anything else is refused).
---@param version string  the version of Hecate, `X.Y.Z`
---@return string
local function quoted_version(version)
  if type(version) ~= "string" or not version:match("^[%w%.%+%-]+$") then
    error(core.ArgumentError("'" .. tostring(version) .. "' is not a version of Hecate that a workflow can name"), 0)
  end
  return '"' .. version .. "-" .. M.REVISION .. '"'
end

--- The `ci` workflow: on every push and pull request, on Linux, macOS and Windows, checks out the project, installs the
--- executable, installs the locked rocks (`install --frozen`), runs the tests, then lints the contract and builds the
--- documentation when asked.
---@param parameters hecate.cli.WorkflowParameters
---@return string text
function M.ci(parameters)
  local version = quoted_version(parameters.hecate_version)
  local lines = {
    "# Generated by `hecate generate workflow ci` (Hecate " .. parameters.hecate_version .. "). Regenerate it with `--force` after an",
    "# upgrade of Hecate. It calls only `hecate` commands, so a run behaves like a local one.",
    "name: ci",
    "",
    "on:",
    "  push:",
    "  pull_request:",
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  ci:",
    "    name: ${{ matrix.os }}",
    "    runs-on: ${{ matrix.os }}",
    "    strategy:",
    "      fail-fast: false",
    "      matrix:",
    "        os: [ubuntu-latest, macos-latest, windows-latest]",
    "    steps:",
    "      - uses: " .. M.CHECKOUT,
    "        with:",
    "          persist-credentials: false",
    "      - name: Set up hecate",
    "        uses: " .. M.SETUP_ACTION .. "@" .. M.SETUP_REF,
    "        with:",
    "          version: " .. version,
    "      - name: Cache the rocks",
    "        uses: " .. M.CACHE,
    "        with:",
    "          path: lua_modules",
    "          key: rocks-${{ runner.os }}-${{ runner.arch }}-${{ hashFiles('hecate.lock') }}",
    "      - name: Install the locked rocks",
    "        run: hecate install --frozen",
    "      - name: Test",
    "        run: hecate test",
  }
  if parameters.contract then
    for _, line in ipairs({
      "      - name: Export the contract",
      "        run: hecate contract export --output openapi.json",
      "      - name: Lint the contract",
      "        run: hecate contract lint openapi.json",
    }) do lines[#lines + 1] = line end
  end
  if parameters.doc then
    lines[#lines + 1] = "      - name: Build the documentation"
    lines[#lines + 1] = "        run: hecate doc build --yes"
  end
  lines[#lines + 1] = ""
  return table.concat(lines, "\n")
end

--- The lines that every job of the other kinds starts with: checkout (the whole history when `full_history`), the setup
--- action and the locked rocks.
---@param version string  the quoted release, `"X.Y.Z-R"`
---@param full_history boolean
---@return string[]
local function setup_lines(version, full_history)
  local lines = {
    "      - uses: " .. M.CHECKOUT,
    "        with:",
    "          persist-credentials: false",
  }
  if full_history then lines[#lines + 1] = "          fetch-depth: 0" end
  for _, line in ipairs({
    "      - name: Set up hecate",
    "        uses: " .. M.SETUP_ACTION .. "@" .. M.SETUP_REF,
    "        with:",
    "          version: " .. version,
    "      - name: Install the locked rocks",
    "        run: hecate install --frozen",
  }) do lines[#lines + 1] = line end
  return lines
end

--- The `contract` workflow: on every pull request, compares the contract committed (`openapi.json`) at the base branch
--- with the contract of the application of the pull request (`hecate contract diff <ref>`) and fails on a breaking
--- change. It needs a project with a `contract` section, and `openapi.json` committed on the base branch
--- (`hecate contract export --output openapi.json`).
---@param parameters hecate.cli.WorkflowParameters
---@return string text
function M.contract(parameters)
  local version = quoted_version(parameters.hecate_version)
  if not parameters.contract then
    error(core.ArgumentError("hecate.project.lua has no `contract` section: add one, for example `contract = { title = \"my-api\", version = \"1.0.0\" }`, then generate the `contract` workflow"), 0)
  end
  local lines = {
    "# Generated by `hecate generate workflow contract` (Hecate " .. parameters.hecate_version .. "). Regenerate it with `--force` after an",
    "# upgrade of Hecate. It needs `openapi.json` committed on the base branch (`hecate contract export --output openapi.json`).",
    "name: contract",
    "",
    "on:",
    "  pull_request:",
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  contract:",
    "    runs-on: ubuntu-latest",
    "    steps:",
  }
  for _, line in ipairs(setup_lines(version, true)) do lines[#lines + 1] = line end
  lines[#lines + 1] = "      - name: Fail on a breaking change of the contract"
  lines[#lines + 1] = "        env:"
  lines[#lines + 1] = "          BASE_REF: ${{ github.base_ref }}"
  lines[#lines + 1] = '        run: hecate contract diff "origin/$BASE_REF"'
  lines[#lines + 1] = ""
  return table.concat(lines, "\n")
end

--- The `docs-pages` workflow: on a push to the default branch (the job runs only there), builds the documentation (`hecate doc build --yes`, into
--- `docs/dist`) and publishes it to GitHub Pages. The site is static with relative links (OQ-148), so it needs no base
--- path. GitHub Pages must be set to the source "GitHub Actions" (Settings, Pages).
---@param parameters hecate.cli.WorkflowParameters
---@return string text
function M.docs_pages(parameters)
  local version = quoted_version(parameters.hecate_version)
  local lines = {
    "# Generated by `hecate generate workflow docs-pages` (Hecate " .. parameters.hecate_version .. "). Regenerate it with `--force` after an",
    "# upgrade of Hecate. Set the source of GitHub Pages to \"GitHub Actions\" (Settings, Pages) once.",
    "name: docs",
    "",
    "on:",
    "  push:",
    "",
    "permissions:",
    "  contents: read",
    "  pages: write",
    "  id-token: write",
    "",
    "concurrency:",
    "  group: pages",
    "  cancel-in-progress: false",
    "",
    "jobs:",
    "  docs:",
    "    if: github.ref_name == github.event.repository.default_branch",
    "    runs-on: ubuntu-latest",
    "    environment:",
    "      name: github-pages",
    "      url: ${{ steps.deployment.outputs.page_url }}",
    "    steps:",
  }
  for _, line in ipairs(setup_lines(version, false)) do lines[#lines + 1] = line end
  for _, line in ipairs({
    "      - name: Build the documentation",
    "        run: hecate doc build --yes",
    "      - name: Configure Pages",
    "        uses: " .. M.CONFIGURE_PAGES,
    "      - name: Upload the site",
    "        uses: " .. M.UPLOAD_PAGES_ARTIFACT,
    "        with:",
    "          path: docs/dist",
    "      - name: Deploy to GitHub Pages",
    "        id: deployment",
    "        uses: " .. M.DEPLOY_PAGES,
    "",
  }) do lines[#lines + 1] = line end
  return table.concat(lines, "\n")
end
M["docs-pages"] = M.docs_pages

return M
