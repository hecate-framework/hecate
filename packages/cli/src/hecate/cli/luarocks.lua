-- LuaRocks orchestration (cli-and-packaging.md, "LuaRocks integration"; spike OQ-2): the isolated configuration, the
-- generated rockspec of a project, the command lines of "install first, pin afterwards", and the reading of what
-- LuaRocks reports. Running a program is injected (`runner`), so everything here is testable without LuaRocks or a
-- network, and the executable supplies the real runner.
global <const> require, load, type, tostring, tonumber, ipairs, pairs, table, error

local core = require("hecate.core")
local lua_text = require("hecate.cli.internal.lua_text")
local sandbox = require("hecate.cli.internal.sandbox")

local quote = lua_text.quote

---@class hecate.cli.RunResult
---@field code integer  exit status of the program
---@field stdout string
---@field stderr string

---@class hecate.cli.RunOptions
---@field env? table<string, string>  added to the environment of the program
---@field cwd? string

---@alias hecate.cli.Runner fun(program: string, args: string[], options: hecate.cli.RunOptions): hecate.cli.RunResult

---@class hecate.cli.InstalledRock
---@field name string
---@field version string
---@field status string  `installed` or what LuaRocks reports otherwise

---@class hecate.cli.OutdatedRock
---@field name string
---@field installed string  the newest version installed
---@field available string  the newest version on the servers
---@field server string  where it is

---@class hecate.cli.LuaRocksOptions
---@field runner hecate.cli.Runner
---@field program? string  the LuaRocks executable (default `luarocks`)
---@field program_arguments? string[]  arguments that make `program` run LuaRocks (the self-contained executable: `--luarocks`); LuaRocks then finds no `lua` on the path, so the program itself is given as the `LUA` variable
---@field tree string  the project-local tree (`lua_modules`)
---@field config_dir string  where the isolated configuration is written (`.hecate/luarocks`)
---@field lua_version? string  default `5.5`
---@field rocks_servers? string[]  default `{ "https://luarocks.org" }`
---@field variables? table<string, string>  LuaRocks `variables` (on Windows `LUA_LIBDIR`, `LUA_INCDIR`, `LUALIB`)

--- The LuaRocks of one project: an isolated configuration, a tree, and a runner.
---@class hecate.cli.LuaRocks
---@field options hecate.cli.LuaRocksOptions
---@overload fun(options: hecate.cli.LuaRocksOptions): hecate.cli.LuaRocks
local LuaRocks = core.class("LuaRocks")

--- Orchestration of LuaRocks.
---@class hecate.cli.luarocks
local M = {}

--- Initialises the LuaRocks of a project. Raises `hecate.core.ArgumentError` when `runner`, `tree` or `config_dir`
--- is missing.
---@param options hecate.cli.LuaRocksOptions
function LuaRocks:init(options)
  if type(options) ~= "table" or type(options.runner) ~= "function" then
    error(core.ArgumentError("luarocks.new: `runner` (a function that runs a program) is required", { context = { argument = "runner" } }), 0)
  end
  if type(options.tree) ~= "string" or options.tree == "" then
    error(core.ArgumentError("luarocks.new: `tree` (the project-local tree) is required", { context = { argument = "tree" } }), 0)
  end
  if type(options.config_dir) ~= "string" or options.config_dir == "" then
    error(core.ArgumentError("luarocks.new: `config_dir` is required", { context = { argument = "config_dir" } }), 0)
  end
  self.options = options
end

--- Creates the LuaRocks of a project (see `LuaRocks:init`).
---@param options hecate.cli.LuaRocksOptions
---@return hecate.cli.LuaRocks
function M.new(options)
  return LuaRocks(options)
end

--- The text of the LuaRocks configuration file: only the project tree, the servers and the variables, so that no
--- user or system setting changes the result.
---@return string text
function LuaRocks:config_text()
  local servers = self.options.rocks_servers or { "https://luarocks.org" }
  local lines = { "-- Generated by hecate; do not edit.", "rocks_trees = {", "  { name = \"project\", root = " .. quote(self.options.tree) .. " },", "}" }
  local quoted = {}
  for index, server in ipairs(servers) do quoted[index] = quote(server) end
  lines[#lines + 1] = "rocks_servers = { " .. table.concat(quoted, ", ") .. " }"
  local names = {}
  for name in pairs(self.options.variables or {}) do names[#names + 1] = name end
  table.sort(names)
  if #names > 0 then
    lines[#lines + 1] = "variables = {"
    for _, name in ipairs(names) do lines[#lines + 1] = "  " .. name .. " = " .. quote(self.options.variables[name]) .. "," end
    lines[#lines + 1] = "}"
  end
  return table.concat(lines, "\n") .. "\n"
end

--- The path of the configuration file and the environment that makes LuaRocks read only it: the user configuration
--- is replaced (`LUAROCKS_CONFIG_<version>`) and the system one is looked up in an empty directory
--- (`LUAROCKS_SYSCONFDIR`).
---@return string config_path
---@return table<string, string> env
function LuaRocks:environment()
  local directory = self.options.config_dir:gsub("[/\\]+$", "")
  local config_path = directory .. "/config.lua"
  local version = (self.options.lua_version or "5.5"):gsub("%.", "_")
  return config_path, {
    ["LUAROCKS_CONFIG_" .. version] = config_path,
    LUAROCKS_CONFIG = config_path, -- the generic variable too: a parent value must not name another file
    LUAROCKS_SYSCONFDIR = directory .. "/system",
  }
end

--- The arguments of a LuaRocks command for this project: the tree is always explicit.
---@param command string[]
---@return string[] args
function LuaRocks:arguments(command)
  local args = {}
  for _, word in ipairs(self.options.program_arguments or {}) do args[#args + 1] = word end
  if self.options.program_arguments then args[#args + 1] = "LUA=" .. (self.options.program or "") end
  args[#args + 1] = "--tree"
  args[#args + 1] = self.options.tree
  for _, word in ipairs(command) do args[#args + 1] = word end
  return args
end

---@async
---@param command string[]
---@param cwd? string
---@return hecate.cli.RunResult
function LuaRocks:run(command, cwd)
  local _, env = self:environment()
  return self.options.runner(self.options.program or "luarocks", self:arguments(command), { env = env, cwd = cwd })
end

--- The rocks installed in the tree, from `luarocks list --porcelain`.
---@async
---@return hecate.cli.InstalledRock[] installed  sorted by name
function LuaRocks:installed()
  local result = self:run({ "list", "--porcelain" })
  if result.code ~= 0 then
    error(core.StateError({ message = "luarocks list failed (exit " .. result.code .. "): " .. result.stderr, context = { stderr = result.stderr } }), 0)
  end
  local installed = {}
  for line in result.stdout:gmatch("[^\r\n]+") do
    local name, version, status = line:match("^(%S+)\t(%S+)\t(%S+)")
    if name then installed[#installed + 1] = { name = name, version = version, status = status } end
  end
  table.sort(installed, function(a, b) return a.name < b.name end)
  return installed
end

--- The rocks of the tree for which a newer version exists on the servers (`luarocks list --outdated --porcelain`, whose
--- lines are tab-separated: name, installed version, available version, server). Needs the network. Raises
--- `hecate.core.StateError` when LuaRocks fails, with what it said.
---@async
---@return hecate.cli.OutdatedRock[] outdated  sorted by name
function LuaRocks:outdated()
  local result = self:run({ "list", "--outdated", "--porcelain" })
  if result.code ~= 0 then
    error(core.StateError({
      message = "luarocks could not look for newer versions (exit " .. result.code .. "): " .. (result.stderr ~= "" and result.stderr or result.stdout),
      context = { stderr = result.stderr },
    }), 0)
  end
  local outdated = {}
  for line in result.stdout:gmatch("[^\r\n]+") do
    local name, installed, available, server = line:match("^(%S+)\t(%S+)\t(%S+)\t(%S*)")
    if name then outdated[#outdated + 1] = { name = name, installed = installed, available = available, server = server } end
  end
  table.sort(outdated, function(a, b) return a.name < b.name end)
  return outdated
end

--- Removes rocks from the tree (`luarocks remove --force`: their dependents are not checked, `update` reinstalls them
--- at once). A rock that is not installed is not an error. Raises `hecate.core.StateError` when LuaRocks fails on one
--- that is installed.
---@async
---@param names string[]
function LuaRocks:remove(names)
  for _, name in ipairs(names) do
    local result = self:run({ "remove", "--force", name })
    if result.code ~= 0 then
      local still = false
      for _, rock in ipairs(self:installed()) do if rock.name == name:lower() or rock.name == name then still = true end end
      if still then
        error(core.StateError({ message = "luarocks could not remove " .. name .. " (exit " .. result.code .. "):\n" .. result.stderr, context = { code = result.code, stderr = result.stderr } }), 0)
      end
    end
  end
end

--- Installs the dependencies of a rockspec into the tree. The exit status is not trusted alone (LuaRocks exits 1 when
--- everything is already installed and a lock is present, spike OQ-2): success is that every rock named in `expected`
--- is installed afterwards. Raises `hecate.core.StateError` naming the missing rocks and what LuaRocks said.
---@param rockspec_path string
---@async
---@param expected string[]  names of the rocks that must be installed
---@return hecate.cli.InstalledRock[] installed
function LuaRocks:install_dependencies(rockspec_path, expected)
  local result = self:run({ "install", "--deps-only", rockspec_path })
  local installed = self:installed()
  local present = {}
  for _, rock in ipairs(installed) do present[rock.name] = rock.status == "installed" end
  local missing = {}
  for _, name in ipairs(expected) do
    if not present[name:lower()] and not present[name] then missing[#missing + 1] = name end
  end
  if #missing > 0 then
    table.sort(missing)
    error(core.StateError({
      message = "luarocks could not install " .. table.concat(missing, ", ") .. " (exit " .. result.code .. "):\n" .. (result.stderr ~= "" and result.stderr or result.stdout),
      context = { missing = missing, code = result.code, stderr = result.stderr },
    }), 0)
  end
  return installed
end

--- Pins the installed versions: `luarocks build --pin --only-deps`, run in `work_dir` (the directory of the
--- generated rockspec, where `luarocks.lock` is written, and which holds no other lock). Only after the dependencies
--- are installed: pinning a fresh tree fails (spike OQ-2). Raises `hecate.core.StateError` when it fails.
---@param rockspec_path string
---@async
---@param work_dir string
function LuaRocks:pin(rockspec_path, work_dir)
  local result = self:run({ "build", "--pin", "--only-deps", rockspec_path }, work_dir)
  if result.code ~= 0 then
    error(core.StateError({ message = "luarocks could not pin the dependencies (exit " .. result.code .. "):\n" .. result.stderr, context = { code = result.code, stderr = result.stderr } }), 0)
  end
end

--- The rockspec that stands for a manifest: its dependencies and development dependencies, and the Lua line. Only
--- `install --deps-only` and `build --pin --only-deps` read it, so there is no source and nothing is built. With
--- `exact` (`install --frozen`: rock name to the version of `hecate.lock`) every locked rock, direct or transitive, is
--- required as `name == version`, so that LuaRocks cannot resolve a newer release (and run its build) before the
--- lockfile is checked.
---@param manifest hecate.cli.Manifest
---@param exact? table<string, string>
---@return string text
function M.rockspec_text(manifest, exact)
  local dependencies = { "lua >= " .. (manifest.lua or "5.5") .. ", < " .. M.next_lua_line(manifest.lua or "5.5") }
  local names = {}
  for name in pairs(manifest.dependencies or {}) do names[#names + 1] = name end
  for name in pairs(manifest.development_dependencies or {}) do
    if (manifest.dependencies or {})[name] == nil then names[#names + 1] = name end
  end
  if exact then
    local listed = {}
    for _, name in ipairs(names) do listed[name:lower()] = true end
    for name in pairs(exact) do
      if not listed[name:lower()] then names[#names + 1] = name; listed[name:lower()] = true end
    end
  end
  table.sort(names)
  for _, name in ipairs(names) do
    local wanted = (manifest.dependencies or {})[name] or (manifest.development_dependencies or {})[name]
    if exact and exact[name] ~= nil then
      dependencies[#dependencies + 1] = name .. " == " .. exact[name]
    else
      dependencies[#dependencies + 1] = (wanted == nil or wanted == "") and name or (name .. " " .. wanted)
    end
  end
  local quoted = {}
  for index, dependency in ipairs(dependencies) do quoted[index] = "  " .. quote(dependency) .. "," end
  return table.concat({
    "-- Generated by hecate from hecate.project.lua; do not edit.",
    'rockspec_format = "3.0"',
    "package = " .. quote(manifest.name),
    "version = " .. quote((manifest.version or "0.0.0") .. "-1"),
    'source = { url = "file:///dev/null" }',
    "dependencies = {",
    table.concat(quoted, "\n"),
    "}",
    'build = { type = "none" }',
    "",
  }, "\n")
end

--- The file name LuaRocks accepts for the rockspec of a manifest: `<name>-<version>-1.rockspec` (it refuses any other
--- shape: "Expected filename in format 'name-version-revision.rockspec'").
---@param manifest hecate.cli.Manifest
---@return string file_name
function M.rockspec_file_name(manifest)
  return manifest.name .. "-" .. (manifest.version or "0.0.0") .. "-1.rockspec"
end

--- `5.5` to `5.6`: the first Lua line a project does not support.
---@param line string
---@return string next_line
function M.next_lua_line(line)
  local major, minor = line:match("^(%d+)%.(%d+)$")
  if not major then
    error(core.ArgumentError("a Lua line looks like '5.5', got '" .. tostring(line) .. "'", { context = { lua = line } }), 0)
  end
  return major .. "." .. (tonumber(minor) + 1)
end

--- Reads a `luarocks.lock` (`return { dependencies = { name = "version", lua = "5.5-1" } }`): the pins by rock name,
--- without the `lua` pseudo-rock, which LuaRocks cannot reinstall from (spike OQ-2). Raises
--- `hecate.core.ConfigurationError` when the text is not a lock.
---@param text string
---@return table<string, string> pins
function M.parse_lock(text)
  local chunk, message = load(text, "=luarocks.lock", "t", {})
  if not chunk then error(core.ConfigurationError({ message = "luarocks.lock: " .. tostring(message) }), 0) end
  local ok, result = sandbox.run(chunk)
  if not ok or type(result) ~= "table" or type(result.dependencies) ~= "table" then
    error(core.ConfigurationError({ message = "luarocks.lock: expected `return { dependencies = { ... } }`" .. (ok and "" or (": " .. tostring(result))) }), 0)
  end
  local pins = {}
  for name, version in pairs(result.dependencies) do
    if type(name) ~= "string" or type(version) ~= "string" then
      error(core.ConfigurationError({ message = "luarocks.lock: a pin must map a rock name to a version string" }), 0)
    end
    if name ~= "lua" then pins[name] = version end
  end
  return pins
end

core.finalise(LuaRocks)

return M
