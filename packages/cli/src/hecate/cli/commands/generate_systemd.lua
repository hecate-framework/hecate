-- `hecate generate systemd [--user <name>] [--workers <n>] [--working-directory <dir>] [--environment-file <file>] [--executable <path>] [--output <file>] [--force]`: the unit
-- file that runs the application of the project as a service (OQ-133: the platform manages the process, `hecate serve`
-- never daemonises; it stops on SIGTERM and reloads on SIGHUP, ADR 0023). The unit goes to the standard output, or to
-- `--output` (an existing file is kept unless `--force`, which prints the unified diff of the existing and the new unit, then
-- overwrites; nothing is rewritten when they are equal).
global <const> require, error, ipairs, string, table, type, tostring

local core = require("hecate.core")
local manifest_module = require("hecate.cli.manifest")
local line_diff = require("hecate.cli.internal.line_diff")

local MANIFEST = "hecate.project.lua"

--- Seconds that systemd waits for a graceful stop: the default `server.grace_timeout` (30 s) and a margin.
local STOP_TIMEOUT = 35

---@class hecate.cli.SystemdOptions
---@field name string  the project name
---@field directory string  the working directory: the project
---@field executable string  the absolute path of the `hecate` executable
---@field user? string  `User=` of the service
---@field workers? string  `--workers` of `hecate serve`
---@field environment_file? string  `EnvironmentFile=` (secrets and per-host settings stay out of the unit and the repository)

--- A path in `WorkingDirectory=`: systemd expands the `%` specifiers in it (systemd.unit(5), "Specifiers"), so a literal `%`
--- is written `%%`; spaces are part of the path.
---@param path string
---@return string
local function path_value(path)
  return (path:gsub("%%", "%%%%"))
end

--- One word of `ExecStart=`: systemd splits the line on spaces, honours quotes and backslash escapes, and expands `$` and
--- `%` (systemd.service(5), "Command lines"). A word with anything but plain characters is put in double quotes, with
--- `\`, `"`, `$` and `%` escaped.
---@param word string
---@return string
local function exec_word(word)
  if word:match("^[%w/._+:@,=%-]+$") then return word end
  return '"' .. word:gsub('[\\"]', "\\%0"):gsub("%$", "$$"):gsub("%%", "%%%%") .. '"'
end

--- The text of the unit file.
---@param options hecate.cli.SystemdOptions
---@return string text
local function unit_text(options)
  local start = exec_word(options.executable) .. " serve" .. (options.workers and (" --workers " .. options.workers) or "")
  local lines = {
    "# Generated by `hecate generate systemd`. Install it as /etc/systemd/system/" .. options.name .. ".service, then",
    "# `systemctl daemon-reload && systemctl enable --now " .. options.name .. "`. `systemctl reload` reloads the primary (SIGHUP).",
    "[Unit]",
    "Description=" .. options.name .. " (Hecate application)",
    "After=network-online.target",
    "Wants=network-online.target",
    "",
    "[Service]",
    "Type=simple",
    "WorkingDirectory=" .. path_value(options.directory),
    "ExecStart=" .. start,
    "ExecReload=/bin/kill -HUP $MAINPID",
    "KillSignal=SIGTERM",
    "TimeoutStopSec=" .. STOP_TIMEOUT,
    "Restart=on-failure",
    "RestartSec=2",
    "Environment=HECATE_ENV=production",
  }
  if options.user then lines[#lines + 1] = "User=" .. options.user end
  if options.environment_file then lines[#lines + 1] = "EnvironmentFile=" .. path_value(options.environment_file) end
  for _, line in ipairs({ "NoNewPrivileges=true", "PrivateTmp=true", "", "[Install]", "WantedBy=multi-user.target", "" }) do
    lines[#lines + 1] = line
  end
  return table.concat(lines, "\n")
end

---@class hecate.cli.SystemdDependencies
---@field fs { read: fun(path: string): string? }
---@field write fun(path: string, text: string)
---@field exists fun(path: string): boolean
---@field run fun(task: fun(): any): any

--- The `generate systemd` command.
---@class hecate.cli.commands.generate_systemd: hecate.cli.Command
---@field execute fun(context: hecate.cli.Context, dependencies: hecate.cli.SystemdDependencies): integer
---@field unit_text fun(options: hecate.cli.SystemdOptions): string
local command = {
  name = "generate systemd",
  summary = "Generate the systemd unit that runs the application",
  options = {
    { name = "user", takes_value = true, summary = "Run the service as this user (User=)" },
    { name = "workers", takes_value = true, summary = "Number of worker processes (a number, or auto)" },
    { name = "working-directory", takes_value = true, summary = "Absolute directory the service runs in (default: the project directory; use the path on the server)" },
    { name = "environment-file", takes_value = true, summary = "Absolute path of a file of NAME=value lines read by the service (EnvironmentFile=)" },
    { name = "executable", takes_value = true, summary = "Absolute path of the hecate executable (default: the running one)" },
    { name = "output", takes_value = true, summary = "Write the unit to this file instead of the standard output" },
    { name = "force", summary = "Overwrite the output file when it exists" },
  },
  unit_text = unit_text,
}

--- Runs the command.
---@param context hecate.cli.Context
---@param dependencies hecate.cli.SystemdDependencies
---@return integer exit_code
function command.execute(context, dependencies)
  local options = context.arguments.options
  local text = dependencies.fs.read(MANIFEST)
  if text == nil then
    error(core.ConfigurationError({ message = MANIFEST .. " not found in the current directory: run `hecate new <name>` to create a project" }), 0)
  end
  local manifest = manifest_module.parse(text)
  local executable = options.executable
  if executable == nil and context.runtime.lua_interpreter_arguments then executable = context.runtime.lua_interpreter end
  if type(executable) ~= "string" or not executable:match("^/") then
    context.print_error("hecate generate systemd: the path of the hecate executable is not known or not absolute: pass --executable /usr/local/bin/hecate")
    return 2
  end
  local user = options.user --[[@as string?]]
  if user ~= nil and (#user > 32 or not user:match("^[%a_][%w_.%-]*$")) then
    context.print_error("hecate generate systemd: --user takes a user name (letters, digits, '_', '.', '-'), got '" .. tostring(user):gsub("%c", "?") .. "'")
    return 2
  end
  -- A line break or any other control character would end the value and let the rest of it add directives to the unit.
  local directory = (options["working-directory"] --[[@as string?]]) or context.runtime.project_dir or "."
  local environment_file = options["environment-file"] --[[@as string?]]
  for _, entry in ipairs({ { "--working-directory", options["working-directory"] }, { "--environment-file", environment_file } }) do
    if entry[2] ~= nil and not tostring(entry[2]):match("^/") then
      context.print_error("hecate generate systemd: " .. entry[1] .. " takes an absolute path (the one on the server), got '" .. tostring(entry[2]):gsub("%c", "?") .. "'")
      return 2
    end
  end
  for _, entry in ipairs({ { "--executable", executable }, { "the working directory", directory }, { "--environment-file", environment_file or "" } }) do
    if entry[2]:find("%c") then
      context.print_error("hecate generate systemd: " .. entry[1] .. " holds a control character (a line break, for example); it cannot go into a unit file")
      return 2
    end
  end
  local workers = options.workers
  if workers ~= nil and not tostring(workers):match("^%d+$") and workers ~= "auto" then
    context.print_error("hecate generate systemd: --workers takes a whole number of at least 1, or auto (got '" .. tostring(workers) .. "')")
    return 2
  end
  local unit = unit_text({
    name = manifest.name, directory = directory, executable = executable,
    user = user, environment_file = environment_file, workers = workers --[[@as string?]],
  })
  local output = options.output --[[@as string?]]
  if output == nil then
    context.emit({ unit = unit }, (unit:gsub("\n$", "")))
    return 0
  end
  local previous = options.force and dependencies.fs.read(output) or nil -- starts a reactor: outside `run`
  local diff, unchanged
  local code = dependencies.run(function()
    if dependencies.exists(output) then
      if not options.force then
        context.print_error("hecate generate systemd: " .. output .. " already exists; pass --force to overwrite it")
        return 1
      end
      diff = line_diff.unified(previous or "", unit, output, output .. " (new)")
      unchanged = diff == nil
      if unchanged then return 0 end
    end
    dependencies.write(output, unit)
    return 0
  end)
  if code ~= 0 then return code end
  if unchanged then
    context.emit({ output = output, unchanged = true }, output .. " is unchanged.")
    return 0
  end
  context.emit({ output = output, diff = diff }, (diff and (diff .. "\n") or "") .. "Wrote " .. output .. ".")
  return 0
end

--- Runs `hecate generate systemd` with the real file system and reactor.
---@param context hecate.cli.Context
---@return integer exit_code
function command.run(context)
  local project_environment = require("hecate.cli.internal.project_environment")
  local reactor = require("hecate.reactor")
  local environment = project_environment.real(context.runtime)
  return command.execute(context, {
    fs = { read = function(path) return reactor.run(function()
      if not reactor.fs.stat(path) then return nil end
      return reactor.fs.read_file(path)
    end) end },
    write = environment.fs.write,
    exists = function(path) return reactor.fs.stat(path) ~= nil end, -- called inside `run`, which is the reactor
    run = environment.run,
  })
end

return command
