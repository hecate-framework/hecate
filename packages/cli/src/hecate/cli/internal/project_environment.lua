-- The real file system, process runner and paths that the commands working on a project share: everything LuaRocks
-- receives is absolute (it runs in the work directory for the pin), built on the project directory.
global <const> require, ipairs, pcall, type

---@class hecate.cli.ProjectEnvironment
---@field fs hecate.cli.InstallFileSystem
---@field luarocks hecate.cli.LuaRocks
---@field work_dir string
---@field tree string
---@field sha256? fun(data: string): string  default: the digest backend of the CLI (tests inject one)
---@field lua_headers? { directory: string, files: table<string, string> }  the headers of the Lua embedded in the executable and where `install` unpacks them (`LUA_INCDIR`); nil when this process is a plain `lua`
---@field run fun(task: fun(): any): any  runs a suspending task to completion (the reactor)

---@class hecate.cli.internal.project_environment
local M = {}

--- The directories to create so that `path` can be written, outermost first, for a relative path, a rooted one
--- (`/home/x/file`) or one with a drive (`C:/Users/x/file`). The root itself and the drive are never listed.
---@param path string  with forward slashes
---@return string[] directories
function M.directories_of(path)
  local directory = path:match("^(.*)/[^/]*$")
  if not directory or directory == "" then return {} end
  local drive = directory:match("^(%a:)")
  local rest = drive and directory:sub(#drive + 1) or directory
  -- `current` starts at the drive, at the root (the empty string, so that the first part is `/part`) or nowhere (relative).
  local current = drive or (rest:sub(1, 1) == "/" and "" or nil)
  local list = {}
  for part in rest:gmatch("[^/]+") do
    current = current == nil and part or (current .. "/" .. part)
    list[#list + 1] = current
  end
  return list
end

--- The headers of the Lua embedded in the executable (the module `hecate.cli.lua_headers`, generated by `build-cli`, absent
--- when the CLI runs on a plain `lua`) and the directory of the project where they are unpacked.
---@param project string  the project directory
---@return { directory: string, files: table<string, string> }? headers
function M.lua_headers(project)
  local ok, files = pcall(require, "hecate.cli.lua_headers")
  if not ok or type(files) ~= "table" then return nil end
  return { directory = project .. "/.hecate/lua/include", files = files }
end

--- The real dependencies: the reactor file system and process runner. LuaRocks runs in the work directory for the pin,
--- so every path it receives is absolute, built on the project directory.
---@param runtime hecate.cli.Runtime
---@return hecate.cli.ProjectEnvironment
function M.real(runtime)
  local reactor = require("hecate.reactor")
  local runner = require("hecate.cli.runner")
  local luarocks = require("hecate.cli.luarocks")
  local project = (runtime.project_dir or "."):gsub("/+$", "")
  local work_dir, tree = project .. "/.hecate/luarocks", project .. "/lua_modules"

  local function ensure_directory(path)
    for _, directory in ipairs(M.directories_of(path)) do
      if not reactor.fs.stat(directory) then reactor.fs.mkdir(directory) end
    end
  end
  ---@type hecate.cli.InstallFileSystem
  local fs = {
    read = function(path)
      if not reactor.fs.stat(path) then return nil end
      return reactor.fs.read_file(path)
    end,
    write = function(path, text)
      ensure_directory(path)
      reactor.fs.write_file(path, text)
    end,
  }
  return {
    fs = fs,
    work_dir = work_dir,
    tree = tree,
    luarocks = luarocks.new({
      runner = runner.run, tree = tree, config_dir = work_dir,
      program = runtime.luarocks_program, program_arguments = runtime.luarocks_arguments,
    }),
    lua_headers = M.lua_headers(project),
    run = function(task) return reactor.run(task) end,
  }
end

return M
