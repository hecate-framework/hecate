local test = require("harness.test")
local app = require("hecate.cli.app")
local workflow = require("hecate.cli.commands.generate_workflow")
local workflows = require("hecate.cli.templates.workflows")
local T = test.Case("CliGenerateWorkflowTest")
local here = debug.getinfo(1, "S").source:match("^@(.*)[/\\][^/\\]*$") or "."
local nested = dofile(here .. "/../support/nested_guard.lua")

local WITH_CONTRACT = 'return { name = "shop", version = "0.1.0", contract = { title = "Shop", version = "1.0.0" } }'
local WITHOUT_CONTRACT = 'return { name = "shop", version = "0.1.0" }'

local function run(args, opts)
  opts = opts or {}
  local written = {}
  local files = opts.manifest == false and {} or { ["hecate.project.lua"] = opts.manifest or WITH_CONTRACT }
  local dependencies = {
    fs = { read = nested.outside(function(path) return files[path] end) },
    write = function(path, text) written[path] = text end,
    exists = function(path) return path == opts.existing end,
    run = nested.run,
  }
  local command = setmetatable({ run = function(context) return workflow.execute(context, dependencies) end }, { __index = workflow })
  local out, err = {}, {}
  local code = app.run(args, {
    commands = { command },
    runtime = { hecate_version = "0.4.2", lua_version = "5.5.1", platform = "linux-x86_64" },
    write = function(text) out[#out + 1] = text end,
    write_error = function(text) err[#err + 1] = text end,
  })
  return code, table.concat(out, "\n"), table.concat(err, "\n"), written
end

local function has(text, fragment, self)
  self:assert_true(text:find(fragment, 1, true) ~= nil, fragment .. "\n" .. text)
end

function T:test_the_ci_workflow_runs_on_three_platforms_with_the_steps_in_order()
  local code, _, _, written = run({ "generate", "workflow", "ci" })
  self:assert_equal(0, code)
  local text = written[".github/workflows/ci.yml"]
  for _, fragment in ipairs({ "  push:\n", "  pull_request:\n", "os: [ubuntu-latest, macos-latest, windows-latest]",
    "uses: " .. workflows.CHECKOUT, "uses: hecate-framework/hecate-setup@" .. workflows.SETUP_REF, 'version: "0.4.2"',
    "Generated by `hecate generate workflow ci` (Hecate 0.4.2)" }) do
    has(text, fragment, self)
  end
  local order = {}
  for _, command in ipairs({ "hecate install --frozen", "hecate test", "hecate contract export --output openapi.json", "hecate contract lint openapi.json" }) do
    order[#order + 1] = assert(text:find("run: " .. command, 1, true), command)
  end
  for index = 2, #order do self:assert_true(order[index - 1] < order[index]) end
  self:assert_true(text:find("hecate doc build", 1, true) == nil)
  self:assert_true(text:find("\t", 1, true) == nil)
end

function T:test_every_third_party_action_is_pinned_by_commit_sha()
  local text = workflows.ci({ hecate_version = "0.4.2", contract = true, doc = true })
  for action in text:gmatch("uses: ([^\n]+)") do
    if not action:match("^hecate%-framework/hecate%-setup@") then
      self:assert_true(action:match("@%x+ # v%d+") ~= nil and #action:match("@(%x+)") == 40, action)
    end
  end
end

function T:test_the_documentation_step_is_optional_and_the_contract_follows_the_manifest()
  local _, _, _, with_doc = run({ "generate", "workflow", "ci", "--doc" })
  has(with_doc[".github/workflows/ci.yml"], "run: hecate doc build --yes", self)
  local _, _, _, without = run({ "generate", "workflow", "ci" }, { manifest = WITHOUT_CONTRACT })
  self:assert_true(without[".github/workflows/ci.yml"]:find("contract", 1, true) == nil)
end

function T:test_output_writes_there_and_an_existing_file_is_kept_unless_forced()
  local code, _, _, written = run({ "generate", "workflow", "ci", "--output=ci.yml" })
  self:assert_equal(0, code)
  self:assert_true(written["ci.yml"] ~= nil)
  local code2, _, err, written2 = run({ "generate", "workflow", "ci" }, { existing = ".github/workflows/ci.yml" })
  self:assert_equal(1, code2)
  has(err, "--force", self)
  self:assert_equal(nil, next(written2))
  local code3, _, _, written3 = run({ "generate", "workflow", "ci", "--force" }, { existing = ".github/workflows/ci.yml" })
  self:assert_equal(0, code3)
  self:assert_true(written3[".github/workflows/ci.yml"] ~= nil)
end

function T:test_the_contract_workflow_diffs_against_the_base_branch_and_needs_a_contract()
  local code, _, _, written = run({ "generate", "workflow", "contract" })
  self:assert_equal(0, code)
  local text = written[".github/workflows/contract.yml"]
  for _, fragment in ipairs({ "  pull_request:\n", "fetch-depth: 0", "uses: " .. workflows.CHECKOUT,
    "uses: hecate-framework/hecate-setup@" .. workflows.SETUP_REF, 'version: "0.4.2"', "BASE_REF: ${{ github.base_ref }}",
    "Generated by `hecate generate workflow contract` (Hecate 0.4.2)" }) do
    has(text, fragment, self)
  end
  local frozen = assert(text:find("run: hecate install --frozen", 1, true))
  self:assert_true(frozen < assert(text:find('run: hecate contract diff "origin/$BASE_REF"', 1, true)))
  self:assert_true(text:find("\t", 1, true) == nil)
  local code2, _, err2, written2 = run({ "generate", "workflow", "contract" }, { manifest = WITHOUT_CONTRACT })
  self:assert_equal(1, code2)
  has(err2, "no `contract` section", self)
  self:assert_equal(nil, next(written2))
  local code3, _, err3 = run({ "generate", "workflow", "contract" }, { existing = ".github/workflows/contract.yml" })
  self:assert_equal(1, code3)
  has(err3, "--force", self)
  local code4, _, _, written4 = run({ "generate", "workflow", "contract", "--force" }, { existing = ".github/workflows/contract.yml" })
  self:assert_equal(0, code4)
  self:assert_true(written4[".github/workflows/contract.yml"] ~= nil)
end

function T:test_the_docs_pages_workflow_builds_and_deploys_with_pinned_actions()
  local code, _, _, written = run({ "generate", "workflow", "docs-pages" }, { manifest = WITHOUT_CONTRACT })
  self:assert_equal(0, code)
  local text = written[".github/workflows/docs.yml"]
  for _, fragment in ipairs({ "  push:\n", "  pages: write\n", "  id-token: write\n", "  contents: read\n",
    "uses: hecate-framework/hecate-setup@" .. workflows.SETUP_REF, "run: hecate install --frozen", "run: hecate doc build --yes",
    "uses: " .. workflows.CONFIGURE_PAGES, "uses: " .. workflows.UPLOAD_PAGES_ARTIFACT, "path: docs/dist",
    "uses: " .. workflows.DEPLOY_PAGES, "default_branch" }) do
    has(text, fragment, self)
  end
  for action in text:gmatch("uses: ([^\n]+)") do
    if not action:match("^hecate%-framework/hecate%-setup@") then
      self:assert_true(action:match("@%x+ # v%d+") ~= nil and #action:match("@(%x+)") == 40, action)
    end
  end
  local code2, _, err2 = run({ "generate", "workflow", "docs-pages" }, { existing = ".github/workflows/docs.yml" })
  self:assert_equal(1, code2)
  has(err2, "--force", self)
  local code3, _, _, written3 = run({ "generate", "workflow", "docs-pages", "--force" }, { existing = ".github/workflows/docs.yml" })
  self:assert_equal(0, code3)
  self:assert_true(next(written3) ~= nil)
end

function T:test_the_kind_and_the_provider_are_checked()
  local code, _, err = run({ "generate", "workflow" })
  self:assert_equal(2, code)
  has(err, "hecate generate workflow ci", self)
  local code2, _, err2 = run({ "generate", "workflow", "release" })
  self:assert_equal(2, code2)
  has(err2, "not implemented yet", self)
  local code3, _, err3 = run({ "generate", "workflow", "nope" })
  self:assert_equal(2, code3)
  has(err3, "unknown kind", self)
  local code4, _, err4 = run({ "generate", "workflow", "ci", "--provider=gitlab" })
  self:assert_equal(2, code4)
  has(err4, "unknown provider", self)
end

function T:test_a_project_is_required()
  local code, _, err = run({ "generate", "workflow", "ci" }, { manifest = false })
  self:assert_true(code ~= 0, tostring(code))
  has(err, "hecate.project.lua", self)
end

function T:test_a_version_that_is_not_plain_is_refused()
  local ok = pcall(workflows.ci, { hecate_version = "1.0\"\n  evil: true" })
  self:assert_false(ok)
end

return T
