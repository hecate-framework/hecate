-- The marker of a generated page: the notice as the first line after the front matter, or `generated: true`.
-- A hand-written page that quotes the notice is not generated: it is never overwritten and never removed.
local test = require("harness.test")
local doc = require("hecate.doc")
local core = require("hecate.core")
local generated_page = require("hecate.doc.internal.generated_page")
local project = require("hecate.doc.project")
local reference = require("hecate.doc.reference")
local front_matter = require("hecate.doc.front_matter")
local T = test.Case("GeneratedMarkerTest")

local NOTICE = generated_page.GENERATED

function T:test_the_notice_is_neutral()
  self:assert_equal("<!-- Generated by hecate.doc. Do not edit; change the project and build again. -->", NOTICE)
  self:assert_equal(NOTICE, project.GENERATED)
end

function T:test_the_notice_first_after_the_front_matter_marks_a_page()
  self:assert_true(generated_page.is_generated(NOTICE .. "\n\n# Title\n"))
  self:assert_true(generated_page.is_generated("---\ntitle: x\n---\n\n" .. NOTICE .. "\n"))
  self:assert_true(generated_page.is_generated("---\r\ntitle: x\r\n---\r\n" .. NOTICE .. "\r\n"))
  self:assert_true(generated_page.is_generated(reference.GENERATED:format("demo") .. "\n"), "the notice of the code reference")
end

function T:test_generated_true_in_the_front_matter_marks_a_page()
  self:assert_true(generated_page.is_generated("---\ngenerated: true\n---\n# Title\n"))
  self:assert_false(generated_page.is_generated("---\ngenerated: false\n---\n# Title\n"))
  self:assert_false(generated_page.is_generated("---\ngenerated: \"yes\"\n---\n# Title\n"))
end

function T:test_a_quoted_notice_does_not_mark_a_page()
  local cases = {
    "# Notice\n\nPages start with " .. NOTICE .. " and so on.\n",
    "# Notice\n\n```html\n" .. NOTICE .. "\n```\n",
    "# Notice\n\n    " .. NOTICE .. "\n",
    "Intro.\n\n" .. NOTICE .. "\n",
    "---\ntitle: x\n---\nIntro\n" .. NOTICE .. "\n",
    "```\n" .. NOTICE .. "\n```\n",
    "  " .. NOTICE .. "\n", -- up to three spaces of indentation are still a comment, but never the exact line
    "# " .. NOTICE .. "\n",
  }
  for index, text in ipairs(cases) do self:assert_false(generated_page.is_generated(text), index .. ": " .. text) end
  self:assert_false(generated_page.is_generated(nil))
  self:assert_false(generated_page.is_generated(3))
  self:assert_false(generated_page.is_generated("---\nbroken\n---\n" .. "x"), "a malformed front matter is not ours")
  self:assert_false(generated_page.is_generated("---\ntitle: x\n"), "an unterminated front matter is not ours")
end

function T:test_the_three_entry_points_are_one_function()
  self:assert_equal(generated_page.is_generated, project.is_generated)
  self:assert_equal(generated_page.is_generated, reference.is_generated)
end

function T:test_project_pages_carry_the_marker_in_both_forms()
  local page = project.configuration_page({ type = "object", properties = { a = { type = "string" } } })
  self:assert_true(generated_page.is_generated(page))
  self:assert_equal(true, front_matter.parse(page).generated)
  self:assert_not_nil(page:find(NOTICE, 1, true))
end

local function options(fs, extra)
  local result = { site_configuration = { title = "Shop" }, guides_dir = "docs", output_dir = "dist", file_system = fs }
  for key, value in pairs(extra or {}) do result[key] = value end
  return result
end

local application = { configuration_schema = function() return { type = "object", properties = { a = { type = "string" } } } end }

local QUOTING = {
  paragraph = "# Configuration\n\nEvery generated page starts with " .. NOTICE .. " and is rewritten.\n",
  fence = "# Configuration\n\n```html\n" .. NOTICE .. "\n```\n",
  indented = "# Configuration\n\nThe notice is:\n\n    " .. NOTICE .. "\n",
}

function T:test_a_guide_that_quotes_the_notice_is_never_overwritten()
  for label, text in pairs(QUOTING) do
    local fs = doc.MemoryFileSystem({ ["docs/en/index.md"] = "# Home\n", ["docs/en/configuration.md"] = text })
    local err = self:assert_error(function() doc.generate_project_documentation(options(fs, { application = application })) end)
    self:assert_true(core.is_instance_of(err, doc.BuildError), label .. ": " .. tostring(err))
    self:assert_equal(text, fs:read("docs/en/configuration.md"), label)
    self:assert_nil(fs:read("dist/en/index.html"), label .. ": nothing was built")
  end
end

function T:test_a_guide_that_quotes_the_notice_is_not_removed_as_stale()
  for label, text in pairs(QUOTING) do
    local fs = doc.MemoryFileSystem({ ["docs/en/index.md"] = "# Home\n", ["docs/en/configuration.md"] = text })
    local report = doc.generate_project_documentation(options(fs))
    self:assert_equal(text, fs:read("docs/en/configuration.md"), label .. ": kept byte for byte")
    self:assert_equal(0, #report.problems, label)
  end
end

function T:test_the_licences_page_is_overwritten_only_when_generated()
  local fs = doc.MemoryFileSystem({ ["docs/en/index.md"] = "# Home\n",
    ["docs/en/third-party-licences.md"] = "# Mine\n\n" .. NOTICE .. " (quoted)\n" })
  local err = self:assert_error(function()
    doc.generate_project_documentation(options(fs, { licences_page = { rocks_tree_dir = "nowhere" } }))
  end)
  self:assert_true(core.is_instance_of(err, doc.BuildError), tostring(err))
  local written = doc.MemoryFileSystem({ ["docs/en/index.md"] = "# Home\n" })
  doc.generate_project_documentation(options(written, { licences_page = { rocks_tree_dir = "nowhere" } }))
  self:assert_true(generated_page.is_generated(written:read("docs/en/third-party-licences.md")))
  doc.generate_project_documentation(options(written, { licences_page = { rocks_tree_dir = "nowhere" } }))
  doc.generate_project_documentation(options(written, {}))
  self:assert_nil(written:read("docs/en/third-party-licences.md"), "a generated page that is no longer produced is removed")
end

function T:test_a_reference_directory_with_a_quoting_guide_is_left_alone()
  local reference_site = require("hecate.doc.reference_site")
  local text = "# Mine\n\n```\n" .. reference.GENERATED:format("demo") .. "\n```\n"
  local fs = doc.MemoryFileSystem({ ["en/reference/demo/mine.md"] = text })
  local problems = reference_site.write(fs, "en", { pages = { ["reference/demo/index.md"] = "x" }, order = { "reference/demo/index.md" }, problems = {} }, { "demo" })
  self:assert_equal(1, #problems)
  self:assert_equal(text, fs:read("en/reference/demo/mine.md"))
end

return T
