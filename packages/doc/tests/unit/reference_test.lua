function T:test_output_is_deterministic_and_independent_of_input_form()
  local first = generate()
  local second = generate({ { name = "demo", export = json.decode(export_text) } })
  self:assert_equal(#first.order, #second.order)
  for index, path in ipairs(first.order) do
    self:assert_equal(path, second.order[index])
    self:assert_equal(first.pages[path], second.pages[path], path)
  end
  for _, content in pairs(first.pages) do
    self:assert_nil(content:find("file://", 1, true))
    self:assert_nil(content:find("/home/", 1, true))
    self:assert_nil(content:find("%d%d%d%d%-%d%d%-%d%d"), "no date in generated pages")
  end
end

function T:test_symbols_of_other_packages_are_linked_when_their_export_is_given()
  local other = {
    { name = "hecate.core.CancellationError", type = "type", rawdesc = " Raised on cancellation.",
      fields = {}, defines = { { type = "doc.class" } } },
    { name = "hecate.core", type = "type", rawdesc = " The core.", fields = {}, defines = { { type = "doc.class" } } },
  }
  local pair = generate({ { name = "core", export = other }, { name = "demo", export = export_text } })
  local wait = pair.pages["reference/demo/functions/wait.md"]
  self:assert_true(wait:find("[`hecate.core.CancellationError`](../../core/CancellationError.md)", 1, true) ~= nil)
  local alone = generate().pages["reference/demo/functions/wait.md"]
  self:assert_true(alone:find("`hecate.core.CancellationError`", 1, true) ~= nil)
  self:assert_nil(alone:find("CancellationError.md", 1, true), "no page, no link")
end

