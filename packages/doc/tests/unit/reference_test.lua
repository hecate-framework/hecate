function T:test_pages_that_would_clash_on_a_case_insensitive_file_system_are_reported()
  local export = json.decode(export_text)
  local copy = json.decode(export_text)
  for _, entry in ipairs(copy) do
    if entry.name == "hecate.demo.Counter" then
      entry.name = "hecate.demo.counter"
      export[#export + 1] = entry
    end
  end
  local result = generate({ { name = "demo", export = export } })
  self:assert_true(#result.problems >= 1)
  self:assert_true(result.problems[1]:find("same page", 1, true) ~= nil)
end

function T:test_invalid_inputs_raise_an_argument_error()
  ---@type any[]
  local invalid = { "x", { { name = 1, export = {} } }, { { name = "demo" } } }
  for _, inputs in ipairs(invalid) do
    local err = self:assert_error(function() reference.generate(inputs) end)
    self:assert_true(core.is_instance_of(err, core.ArgumentError))
  end
end

function T:test_the_writer_replaces_the_pages_of_a_package_and_refuses_a_hand_written_directory()
  local memory = doc.MemoryFileSystem({
    ["en/reference/demo/Stale.md"] = reference.GENERATED:format("demo") .. "\n",
    ["en/reference/demo/functions/old.md"] = reference.GENERATED:format("demo") .. "\n",
    ["en/reference/glossary.md"] = "# Glossary\n",
    ["en/reference/other/Mine.md"] = "# Written by hand\n",
  })
  local result = generate()
  local problems = reference_site.write(memory, "en", result, { "demo", "other" })
  self:assert_equal(1, #problems)
  self:assert_true(problems[1]:find("other", 1, true) ~= nil)
  self:assert_nil(memory:read("en/reference/demo/Stale.md"), "a stale generated page is removed")
  self:assert_nil(memory:read("en/reference/demo/functions/old.md"))
  self:assert_not_nil(memory:read("en/reference/demo/index.md"))
  self:assert_equal("# Glossary\n", memory:read("en/reference/glossary.md"), "hand-written pages are untouched")
  self:assert_equal("# Written by hand\n", memory:read("en/reference/other/Mine.md"))
end

function T:test_a_site_with_the_generated_pages_builds_in_strict_mode_with_a_sidebar_entry_per_page()
  local files = {
    ["site.lua"] = "return { title = 'demo', nav = { { text = 'Reference', link = 'reference/' } } }",
    ["en/index.md"] = "---\ntitle: Home\n---\n\n# Home\n\nSee the [reference](reference/demo/index.md).\n",
  }
  local result = generate()
  for path, content in pairs(result.pages) do files["en/" .. path] = content end
  local memory = doc.MemoryFileSystem(files)
  local report = doc.build({
    config = doc.load_config("site.lua", memory), source = ".", out = "dist", fs = memory, strict = true,
  })
  self:assert_equal(0, #report.problems, table.concat(report.problems, "\n"))
  local page = memory:read("dist/en/reference/demo/Counter/index.html")
  self:assert_not_nil(page)
  for _, url in ipairs({ "/en/reference/demo/", "/en/reference/demo/CounterError/", "/en/reference/demo/functions/add/",
    "/en/reference/demo/functions/wait/" }) do
    self:assert_true(page:find('href="' .. url .. '"', 1, true) ~= nil, "sidebar entry " .. url)
  end
  self:assert_true(page:find('id="wait_for"', 1, true) ~= nil, "a member has a stable anchor")
end

return T
