function T:test_a_pipe_in_a_type_does_not_break_the_table()
  local export = json.decode(export_text)
  for _, entry in ipairs(export) do
    if entry.name == "hecate.demo" then
      for _, field in ipairs(entry.fields) do
        if field.name == "add" and field.extends and field.extends.args then field.extends.args[1].view = "integer|string" end
      end
    end
  end
  local add = generate({ { name = "demo", export = export } }).pages["reference/demo/functions/add.md"]
  self:assert_true(add:find("| `a` | `integer\\|string` |", 1, true) ~= nil)
end

