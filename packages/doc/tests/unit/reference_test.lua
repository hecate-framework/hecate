---@diagnostic disable: need-check-nil, undefined-field  -- tests index generated pages that a failing assertion would reveal
-- The reference generator: the nine-section template, the marks of generated pages, links,
-- determinism, the golden pages of the fixture package, and the writer that replaces them.
-- To accept a deliberate change of the output: HECATE_DOC_UPDATE_GOLDEN=1 lua tools/run.lua test doc
local test = require("harness.test")
local doc = require("hecate.doc")
local reference = require("hecate.doc.reference")
local reference_site = require("hecate.doc.reference_site")
local json = require("hecate.doc.internal.json")
local core = require("hecate.core")
local T = test.Case("ReferenceTest")

local fixtures = (debug.getinfo(1, "S").source:sub(2):gsub("\\", "/"):match("^(.*)/unit/")) .. "/fixtures/reference"
local fs = doc.SystemFileSystem()

local function read(path)
  local file = io.open(path, "rb")
  if not file then return nil end
  local text = file:read("a")
  file:close()
  return text
end

local export_text = assert(read(fixtures .. "/export.json"))

local function examples(symbol)
  if symbol == "hecate.demo.add" then
    return read(fixtures .. "/root/packages/demo/examples/hecate.demo.add.lua"), "packages/demo/examples/hecate.demo.add.lua"
  end
end

local function generate(inputs, options)
  return reference.generate(inputs or { { name = "demo", export = export_text } }, options or { examples = examples })
end

local SECTIONS = {
  "## Syntax", "## Parameters and return values", "## Errors raised", "## May suspend", "## Examples",
  "## Specifications and standards", "## Compatibility", "## See also",
}

--- Positions of the template sections in a page: they must exist and be in this order.
local function assert_sections_in_order(self, content, path)
  local position = 0
  for _, heading in ipairs(SECTIONS) do
    local found = content:find("\n" .. heading .. "\n", position + 1, true)
    self:assert_not_nil(found, path .. " lacks " .. heading)
    self:assert_true(found > position, path .. ": " .. heading .. " is out of order")
    position = found
  end
end

function T:test_undocumented_bare_fields_are_skipped_without_renaming_the_members_that_are_kept()
  -- Regression: a skipped field used to overwrite the name of the member kept before it (or fail
  -- when it came first), depending on the iteration order of a table: many of them make it certain.
  local entries = json.decode(export_text)
  local module
  for _, entry in ipairs(entries) do
    if entry.name == "hecate.demo" then module = entry end
  end
  self:assert_not_nil(module, "the fixture export has the module hecate.demo")
  for index = 1, 40 do
    module.fields[#module.fields + 1] = { name = "bare_" .. index, type = "setfield", visible = "public", rawdesc = "", view = "any" }
  end
  local pages = generate({ { name = "demo", export = json.encode(entries) } }).pages
  self:assert_not_nil(pages["reference/demo/functions/add.md"])
  for path in pairs(pages) do self:assert_nil(path:find("bare_", 1, true), path) end
  self:assert_nil(pages["reference/demo/index.md"]:find("bare_", 1, true))
end

function T:test_the_fixture_package_renders_to_the_golden_pages()
  local result = generate()
  self:assert_equal(0, #result.problems, table.concat(result.problems, "\n"))
  local update = os.getenv("HECATE_DOC_UPDATE_GOLDEN")
  for _, path in ipairs(result.order) do
    if update then fs:write(fixtures .. "/golden/" .. path, result.pages[path]) end
    local expected = read(fixtures .. "/golden/" .. path)
    self:assert_not_nil(expected, "missing golden page " .. path .. "; run with HECATE_DOC_UPDATE_GOLDEN=1")
    self:assert_equal(expected, result.pages[path], path)
  end
  local listed = {}
  for _, entry in ipairs(fs:list(fixtures .. "/golden/reference/demo") or {}) do
    if not entry.is_directory then listed[#listed + 1] = entry.name end
  end
  self:assert_equal(4, #listed, "a golden page that the generator no longer writes must be deleted")
end

function T:test_every_page_is_marked_as_generated_and_has_front_matter()
  local result = generate()
  self:assert_true(#result.order >= 8)
  for _, path in ipairs(result.order) do
    local content = result.pages[path]
    self:assert_true(reference.is_generated(content), path)
    self:assert_true(content:find("Do not edit", 1, true) ~= nil, path)
    local meta, body = doc.front_matter.parse(content, path)
    self:assert_true(meta.generated, path)
    self:assert_true(meta.title ~= nil and meta.title ~= "", path)
    self:assert_true(meta.description ~= nil and meta.description ~= "", path)
    self:assert_true(body:find("^%s*<!%-%- Generated by hecate%.doc") ~= nil, path .. ": the marker comes first")
  end
end

function T:test_function_and_class_pages_follow_the_nine_section_template()
  local result = generate()
  for _, path in ipairs(result.order) do
    local content = result.pages[path]
    self:assert_true(content:find("\n# hecate%.demo") ~= nil, path)
    assert_sections_in_order(self, content, path)
  end
end

