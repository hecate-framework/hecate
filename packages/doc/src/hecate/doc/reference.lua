-- The code reference: Markdown pages from the JSON export of `lua-language-server --doc`
-- (documentation.md, "Generated reference" and "Reference page template"). The generator only
-- reads what LuaLS exports; the annotation conventions that make the export complete are in
-- coding-standards.md, "Annotations for the reference". Pure: it takes decoded exports and
-- returns pages, so the output is deterministic (names sorted, no dates, no absolute paths).
--
-- Export format: pinned to LuaLS 3.19.1 (tests/fixtures/reference/export.json is a real export
-- and tests/integration/reference_test.lua compares it with a fresh one when LuaLS is installed).
global <const> require, type, ipairs, pairs, table, string, error, tostring, pcall, setmetatable

local core = require("hecate.core")
local json = require("hecate.doc.internal.json")

local M = {}

M.GENERATED = "<!-- Generated by hecate.doc from the LuaLS export (lua tools/run.lua gen-reference). "
  .. "Do not edit: change the annotations in packages/%s/src and generate again. -->"

---@class hecate.doc.ReferenceInput
---@field name string  package name ("reactor"): pages go below `reference/<name>/`
---@field export string|table  the JSON text of the export, or its decoded form

---@class hecate.doc.ReferenceOptions
---@field since? string  version that introduced symbols without a `Since` paragraph (default "0.x")
---@field order_of? table<string, integer>  `order` front matter of the module page of each package (set by `generate`)
---@field examples? fun(symbol: string): string?, string?  source and path of the tested example of a symbol
---@field root? string  directory of the pages below the locale root (default "reference")

---@class hecate.doc.ReferenceResult
---@field pages table<string, string>  path below the locale root ("reference/core/class.md") to Markdown
---@field problems string[]  names that clash, exports that cannot be read
---@field order string[]  the paths in generation order

-- Text ---------------------------------------------------------------------------------

--- Splits the description LuaLS keeps for a symbol into paragraphs and removes what LuaLS
--- adds itself: generated `return #n:` code blocks, absolute `file://` links and the `See:`
--- lines of `---@see`.
---@param text string?
---@return string[] paragraphs
---@return string[] see  names given to `---@see`
local function paragraphs_of(text)
  local paragraphs, see = {}, {}
  if text == nil or text == "" then return paragraphs, see end
  text = text:gsub("\r\n", "\n")
  text = text:gsub("%[([^%]\n]*)%]%(file://[^)\n]*%)", "%1")
  local current, in_fence, skipping = {}, false, false
  local function flush()
    if #current > 0 then paragraphs[#paragraphs + 1] = table.concat(current, "\n") end
    current = {}
  end
  local lines = {}
  for line in (text .. "\n"):gmatch("([^\n]*)\n") do lines[#lines + 1] = line end
  local index = 1
  while index <= #lines do
    local line = lines[index]:gsub("^ ", "")
    if skipping then
      if line:find("^```") then skipping = false end
    elseif in_fence then
      current[#current + 1] = line
      if line:find("^```") then in_fence = false end
    elseif line:find("^```") then
      local nxt = (lines[index + 1] or ""):gsub("^ ", "")
      if nxt:find("^return #%d+:") or nxt:find("^param [%w_.]+:") then
        skipping = true
      else
        in_fence = true
        current[#current + 1] = line
      end
    elseif line:find("^See: ") then
      local name = line:match("^See: ~([^~]+)~") or line:match("^See: (.+)$")
      if name then see[#see + 1] = name end
    elseif line:find("^%s*$") then
      flush()
    else
      current[#current + 1] = line
    end
    index = index + 1
  end
  flush()
  return paragraphs, see
end

local function one_line(text)
  return (text:gsub("%s+", " "):gsub("^ ", ""):gsub(" $", ""))
end

local function plain(text)
  text = text:gsub("%[([^%]]*)%]%([^)]*%)", "%1"):gsub("`", "")
  return one_line(text)
end

local function quote(text)
  return '"' .. one_line(text):gsub("\\", "\\\\"):gsub('"', '\\"') .. '"'
end

local function cell(text)
  return (one_line(text):gsub("|", "\\|"))
end

