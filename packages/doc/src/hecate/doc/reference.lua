---@class hecate.doc.ReferenceParameter
---@field name string
---@field type string
---@field description string
---@field optional boolean

---@class hecate.doc.ReferenceMember
---@field name string
---@field kind "function"|"method"|"field"
---@field async boolean
---@field summary string
---@field details string[]  paragraphs after the summary
---@field raises string[]  paragraphs that start with `Raises`
---@field implements string[]  paragraphs that start with `Implements`
---@field since? string
---@field see string[]
---@field parameters hecate.doc.ReferenceParameter[]
---@field returns hecate.doc.ReferenceParameter[]
---@field type? string  type of a field
---@field documented boolean
---@field file? string  source file below the `src` of the package, as reported by LuaLS

--- Classifies the paragraphs of a description.
local function classify(member, paragraphs, see)
  member.see = see
  member.details, member.raises, member.implements = {}, {}, {}
  member.summary = ""
  for index, paragraph in ipairs(paragraphs) do
    if paragraph:find("^Raises ") then
      member.raises[#member.raises + 1] = paragraph
    elseif paragraph:find("^Implements ") then
      member.implements[#member.implements + 1] = paragraph
    elseif paragraph:find("^Since [%w_.%-]+%.?$") then
      member.since = paragraph:match("^Since ([%w_.%-]-)%.?$")
    elseif index == 1 then
      member.summary = paragraph
    else
      member.details[#member.details + 1] = paragraph
    end
  end
  member.documented = #paragraphs > 0
end

local function parameter(entry)
  local view = entry.view or "any"
  return {
    name = entry.name or "...",
    type = view,
    description = entry.desc and entry.desc ~= "" and entry.desc or "",
    optional = view:find("%?$") ~= nil,
  }
end

--- Reads parameters and returns from the `extends` of a function member.
local function signature_of(member, extends, is_method)
  member.parameters, member.returns = {}, {}
  if type(extends) ~= "table" then return end
  if extends.type == "function" then
    for _, argument in ipairs(extends.args or {}) do
      if not (is_method and argument.name == "self") then
        member.parameters[#member.parameters + 1] = parameter(argument)
      end
    end
    for _, entry in ipairs(extends.returns or {}) do
      local item = parameter(entry)
      item.name = entry.name or ""
      if not (item.type == "unknown" and item.description == "") then member.returns[#member.returns + 1] = item end
    end
  else
    -- `---@field name fun(a: string): number`: the types are the only information.
    local fn = extends.types and extends.types[1]
    if fn and fn.type == "doc.type.function" then
      for _, argument in ipairs(fn.args or {}) do
        local name = argument.name and (argument.name[1] or argument.name.view) or "..."
        member.parameters[#member.parameters + 1] = {
          name = name, type = argument.view or "any", description = "", optional = (argument.view or ""):find("%?$") ~= nil,
        }
      end
      for _, entry in ipairs(fn.returns or {}) do
        member.returns[#member.returns + 1] = { name = "", type = entry.view or "any", description = "", optional = false }
      end
    end
  end
end

local function is_function_field(field)
  if field.type == "setmethod" then return true end
  local extends = field.extends
  if type(extends) ~= "table" then return false end
  if extends.type == "function" then return true end
  local first = extends.types and extends.types[1]
  return first ~= nil and first.type == "doc.type.function"
end

--- How informative a duplicate of a member is: a documented function beats a bare assignment.
local function score(field)
  local value = 0
  if field.rawdesc and field.rawdesc ~= "" then value = value + 4 end
  if type(field.extends) == "table" and field.extends.args and #field.extends.args > 0 then value = value + 2 end
  if type(field.extends) == "table" and field.extends.returns and #field.extends.returns > 0 then value = value + 1 end
  if field.type == "doc.field" then value = value + 1 end
  return value
end

local function member_of(field)
  local member = { name = field.name, async = field.async == true, file = field.file }
  local paragraphs, see = paragraphs_of(field.rawdesc)
  classify(member, paragraphs, see)
  if is_function_field(field) then
    member.kind = field.type == "setmethod" and "method" or "function"
    signature_of(member, field.extends, member.kind == "method")
    if member.kind == "function" and field.extends and field.extends.type == "function" then
      member.async = member.async or (field.extends.view or ""):find("^%(async%)") ~= nil
    end
  else
    member.kind = "field"
    member.parameters, member.returns = {}, {}
    member.type = (type(field.extends) == "table" and field.extends.view) or field.view or "any"
  end
  return member
end

--- Builds the members of a class entry: public, deduplicated, sorted by name.
local function members_of(entry)
  local best = {}
  for _, field in ipairs(entry.fields or {}) do
    local name = field.name
    if type(name) == "string" and name:sub(1, 1) ~= "_" and field.visible ~= "private"
      and field.visible ~= "protected" then
      local keep = best[name]
      if keep == nil or score(field) > score(keep) then best[name] = field end
    end
  end
  local members = {}
  for name, field in pairs(best) do
    local member = member_of(field)
    -- A bare assignment of a value without a description is not documentation.
    if member.kind ~= "field" or field.type == "doc.field" or member.documented then
      members[#members + 1] = member
    end
  end
  table.sort(members, function(a, b) return a.name < b.name end)
  return members
end

local function extends_of(entry)
  local names = {}
  for _, definition in ipairs(entry.defines or {}) do
    if type(definition.extends) == "table" then
      for _, parent in ipairs(definition.extends) do
        if parent.view then names[#names + 1] = parent.view end
      end
    end
  end
  table.sort(names)
  local unique, last = {}, nil
  for _, name in ipairs(names) do
    if name ~= last then unique[#unique + 1] = name end
    last = name
  end
  return unique
end

local function is_alias(entry)
  for _, definition in ipairs(entry.defines or {}) do
    if definition.type == "doc.alias" then return true end
  end
  return false
end

---@class hecate.doc.ReferenceClass
---@field name string  full name ("hecate.reactor.Future")
---@field short string  last segment
---@field package_name string
---@field kind "Module"|"Class"|"Type"|"Error class"
---@field is_root boolean  the module table of the package
---@field summary string
---@field details string[]
---@field raises string[]
---@field implements string[]
---@field since? string
---@field see string[]
---@field extends string[]
---@field members hecate.doc.ReferenceMember[]
---@field path string  page path below the locale root
---@field file? string  source file below the `src` of the package, as reported by LuaLS

local function build_classes(inputs, root, problems)
  local classes, by_name = {}, {}
  for _, input in ipairs(inputs) do
    local decoded = input.export
    if type(decoded) == "string" then
      local ok, value = pcall(json.decode, decoded)
      if not ok then
        problems[#problems + 1] = ("package %s: the LuaLS export cannot be read: %s"):format(input.name, tostring(value))
        decoded = {}
      else
        decoded = value
      end
    end
    local prefix = "hecate." .. input.name
    for _, entry in ipairs(decoded) do
      local name = entry.name
      if entry.type == "type" and type(name) == "string"
        and (name == prefix or name:sub(1, #prefix + 1) == prefix .. ".")
        and not name:find(".internal.", 1, true) and not is_alias(entry) then
        local paragraphs, see = paragraphs_of(entry.rawdesc)
        local class = { name = name, package_name = input.name, short = name:match("([^.]+)$"), see = {} }
        classify(class, paragraphs, see)
        class.is_root = name == prefix
        for _, definition in ipairs(entry.defines or {}) do
          if definition.type == "doc.class" and type(definition.file) == "string" then
            class.file = definition.file
            break
          end
        end
        class.extends = extends_of(entry)
        class.members = members_of(entry)
        class.path = class.is_root and ("%s/%s/index.md"):format(root, input.name)
          or ("%s/%s/%s.md"):format(root, input.name, class.short)
        classes[#classes + 1] = class
        by_name[name] = class
      end
    end
  end
  table.sort(classes, function(a, b) return a.name < b.name end)
  -- Kinds, once every class is known (error classes are found through their parents).
  local function is_error(class, depth)
    if class.name == "hecate.core.Error" then return true end
    if depth > 16 then return false end
    for _, parent in ipairs(class.extends) do
      if parent == "hecate.core.Error" then return true end
      local known = by_name[parent]
      if known and is_error(known, depth + 1) then return true end
    end
    return false
  end
  for _, class in ipairs(classes) do
    local has_methods, has_functions = false, false
    for _, member in ipairs(class.members) do
      if member.kind == "method" then has_methods = true elseif member.kind == "function" then has_functions = true end
    end
    if class.is_root then
      class.kind = "Module"
    elseif is_error(class, 0) then
      class.kind = "Error class"
    elseif has_methods then
      class.kind = "Class"
    elseif has_functions then
      class.kind = "Module"
    else
      class.kind = "Type"
    end
  end
  return classes, by_name
end

-- Links --------------------------------------------------------------------------------

local function relative(from, to)
  local from_parts, to_parts = {}, {}
  for part in from:gmatch("[^/]+") do from_parts[#from_parts + 1] = part end
  for part in to:gmatch("[^/]+") do to_parts[#to_parts + 1] = part end
  from_parts[#from_parts] = nil -- the file name
  local common = 0
  while common < #from_parts and common < #to_parts - 1 and from_parts[common + 1] == to_parts[common + 1] do
    common = common + 1
  end
  local parts = {}
  for _ = common + 1, #from_parts do parts[#parts + 1] = ".." end
  for index = common + 1, #to_parts do parts[#parts + 1] = to_parts[index] end
  return table.concat(parts, "/")
end

---@class hecate.doc.ReferenceContext
---@field targets table<string, string>  symbol name to page path (with `#anchor` for members)
---@field page string  path of the page being written

local function link(context, name, label)
  local target = context.targets[name]
  label = label or ("`" .. name .. "`")
  if not target then return label end
  local path, anchor = target:match("^([^#]*)(#?.*)$")
  local url = path == context.page and "" or relative(context.page, path)
  return ("[%s](%s%s)"):format(label, url, anchor)
end

--- Links the symbols named in backticks that have a page; leaves code blocks alone.
local function link_prose(context, text)
  local out, in_fence = {}, false
  for line in (text .. "\n"):gmatch("([^\n]*)\n") do
    if line:find("^```") then in_fence = not in_fence end
    local result = line
    if not in_fence and not line:find("^```") then
      result = line:gsub("`([%w_.:]+)`", function(name)
        if context.targets[name] then return link(context, name) end
        return nil
      end)
    end
    out[#out + 1] = result
  end
  return table.concat(out, "\n")
end

local function type_cell(context, text)
  if context.targets[text] then return link(context, text) end
  return "`" .. cell(text) .. "`"
end

-- Rendering ----------------------------------------------------------------------------

-- Repository path of the source file that holds the documentation comments.
local function source_of(package_name, file)
  return file and ("packages/%s/src/%s"):format(package_name, file) or nil
end

local function page(meta, package_name, heading, body)
  local out = { "---" }
  out[#out + 1] = "title: " .. quote(meta.title)
  out[#out + 1] = "description: " .. quote(meta.description)
  out[#out + 1] = 'hecate: "0.x"'
  out[#out + 1] = 'lua: "5.5"'
  if meta.order then out[#out + 1] = "order: " .. meta.order end
  out[#out + 1] = "generated: true"
  if meta.source then out[#out + 1] = "source: " .. quote(meta.source) end
  out[#out + 1] = "---"
  out[#out + 1] = ""
  out[#out + 1] = M.GENERATED:format(package_name)
  out[#out + 1] = ""
  out[#out + 1] = "# " .. heading
  out[#out + 1] = ""
  out[#out + 1] = table.concat(body, "\n")
  return table.concat(out, "\n"):gsub("\n+$", "") .. "\n"
end

local function alias_of(class)
  return class.is_root and class.short or class.short
end

local function parameter_names(member, mark_optional)
  local names = {}
  for _, item in ipairs(member.parameters) do
    names[#names + 1] = item.name .. ((mark_optional and item.optional and item.name ~= "...") and "?" or "")
  end
  return table.concat(names, ", ")
end

local function declaration(class_alias, member)
  local lines = {}
  if member.async then lines[#lines + 1] = "---@async" end
  for _, item in ipairs(member.parameters) do
    local name = item.name
    local kind = item.type
    if item.optional and name ~= "..." then
      name = name .. "?"
      kind = kind:gsub("%?$", "")
    end
    lines[#lines + 1] = ("---@param %s %s"):format(name, kind)
  end
  for _, item in ipairs(member.returns) do
    lines[#lines + 1] = ("---@return %s%s"):format(item.type, item.name ~= "" and (" " .. item.name) or "")
  end
  local separator = member.kind == "method" and ":" or "."
  lines[#lines + 1] = ("function %s%s%s(%s) end"):format(class_alias, separator, member.name, parameter_names(member, false))
  return table.concat(lines, "\n")
end

--- Removes the trailing `?` of an optional type, and the parentheses LuaLS adds around a union.
local function without_optional(text)
  local base = text:match("^(.-)%?$") or text
  return (base:match("^%((.*)%)$") or base)
end

--- `is_parameter`: an optional parameter is marked on its name; an optional return keeps `?` on its type.
local function parameter_table(context, items, is_parameter)
  local out = { "| Name | Type | Description |", "|---|---|---|" }
  for _, item in ipairs(items) do
    local name, kind = item.name, item.type
    if is_parameter and item.optional then
      kind = without_optional(kind)
      if name ~= "..." then name = name .. "?" end
    end
    local row = { name ~= "" and ("`" .. name .. "`") or "-", type_cell(context, kind),
      item.description ~= "" and cell(link_prose(context, item.description)) or "-" }
    out[#out + 1] = "| " .. table.concat(row, " | ") .. " |"
  end
  return table.concat(out, "\n")
end

local function has_optional(items)
  for _, item in ipairs(items) do if item.optional then return true end end
  return false
end

--- The "Parameters" and "Return values" parts of a function or method.
local function io_sections(context, member, heading)
  local out = {}
  local function label(text) return heading == "**" and ("**" .. text .. "**") or (heading .. " " .. text) end
  out[#out + 1] = label("Parameters")
  out[#out + 1] = ""
  if #member.parameters == 0 then
    out[#out + 1] = "None."
  else
    out[#out + 1] = parameter_table(context, member.parameters, true)
  end
  out[#out + 1] = ""
  out[#out + 1] = label("Return values")
  out[#out + 1] = ""
  if #member.returns == 0 then
    out[#out + 1] = "Returns nothing."
  else
    out[#out + 1] = parameter_table(context, member.returns, false)
    if has_optional(member.returns) then
      out[#out + 1] = ""
      out[#out + 1] = "A type that ends in `?` includes `nil`, returned for an expected absence "
        .. "([ADR 0018](https://github.com/hecate-framework/hecate/blob/main/docs/adr/0018-error-signalling.md))."
    end
  end
  return table.concat(out, "\n")
end

local function raises_text(context, member)
  if #member.raises == 0 then return nil end
  local out = {}
  for _, paragraph in ipairs(member.raises) do out[#out + 1] = link_prose(context, paragraph) end
  return table.concat(out, "\n\n")
end

local SUSPENDS = "May suspend the running coroutine (`---@async`): other computations run while it "
  .. "waits. Call it from a coroutine managed by the reactor."

local function see_list(context, names)
  local out = {}
  local seen = {}
  for _, entry in ipairs(names) do
    if not seen[entry.name] then
      seen[entry.name] = true
      out[#out + 1] = "- " .. link(context, entry.name, entry.label)
    end
  end
  return #out > 0 and table.concat(out, "\n") or "None."
end

local function example_section(options, symbol)
  if not options.examples then return "None yet." end
  local source, path = options.examples(symbol)
  if not source then return "None yet." end
  return ("```lua\n%s\n```\n\nSource: `%s`, run by the tests of the package."):format(source:gsub("\n+$", ""), path or "")
end

local function standards_text(context, subject)
  if #subject.implements == 0 then return "None." end
  local out = {}
  for _, paragraph in ipairs(subject.implements) do out[#out + 1] = link_prose(context, paragraph) end
  return table.concat(out, "\n\n")
end

local function compatibility_text(options, subject)
  return ("Introduced in hecate %s. Lua 5.5."):format(subject.since or options.since or "0.x")
end

local function summary_block(context, subject)
  local out = {}
  out[#out + 1] = subject.summary ~= "" and link_prose(context, subject.summary) or "No description yet."
  for _, paragraph in ipairs(subject.details) do out[#out + 1] = link_prose(context, paragraph) end
  return table.concat(out, "\n\n")
end

local function see_entries(context, subject, extra)
  local entries = {}
  for _, name in ipairs(extra or {}) do entries[#entries + 1] = { name = name } end
  for _, name in ipairs(subject.see) do entries[#entries + 1] = { name = name } end
  return see_list(context, entries)
end

--- Page of one function of a module (the nine sections of the template).
local function render_function(context, options, class, member)
  local symbol = class.name .. "." .. member.name
  local alias = alias_of(class)
  local body = {}
  local function add(...) for _, text in ipairs({ ... }) do body[#body + 1] = text; body[#body + 1] = "" end end
  add(summary_block(context, member))
  add("## Syntax", "```lua\n" .. declaration(alias, member) .. "\n```")
  add("## Parameters and return values", io_sections(context, member, "###"))
  add("## Errors raised", raises_text(context, member) or "None documented.")
  add("## May suspend", member.async and SUSPENDS or "Does not suspend.")
  add("## Examples", example_section(options, symbol))
  add("## Specifications and standards", standards_text(context, member))
  add("## Compatibility", compatibility_text(options, member))
  add("## See also", see_entries(context, member, { class.name }))
  local meta = {
    title = member.name,
    description = plain(member.summary ~= "" and member.summary or (symbol .. ".")),
    source = source_of(class.package_name, member.file or class.file),
  }
  return page(meta, class.package_name, symbol, body)
end

local function member_signature(class, member)
  local alias = alias_of(class)
  local separator = member.kind == "method" and ":" or "."
  local line = ("%s%s%s(%s)"):format(alias, separator, member.name, parameter_names(member, true))
  if #member.returns > 0 then
    local returns = {}
    for _, item in ipairs(member.returns) do
      returns[#returns + 1] = item.type .. (item.name ~= "" and (" " .. item.name) or "")
    end
    line = line .. " -> " .. table.concat(returns, ", ")
  end
  return line
end

--- A member of a class (field, function or method): the heading with a stable anchor and its details.
local function render_member(context, class, member)
  local out = {}
  local label = member.kind == "method" and (alias_of(class) .. ":" .. member.name)
    or member.kind == "function" and (alias_of(class) .. "." .. member.name) or member.name
  out[#out + 1] = ("#### `%s` {#%s}"):format(label, member.name)
  out[#out + 1] = ""
  out[#out + 1] = member.summary ~= "" and link_prose(context, member.summary) or "No description yet."
  for _, paragraph in ipairs(member.details) do
    out[#out + 1] = ""
    out[#out + 1] = link_prose(context, paragraph)
  end
  out[#out + 1] = ""
  if member.kind == "field" then
    out[#out + 1] = "Type: " .. type_cell(context, member.type or "any") .. "."
  else
    out[#out + 1] = "```lua\n" .. member_signature(class, member) .. "\n```"
    if member.async then
      out[#out + 1] = ""
      out[#out + 1] = "**May suspend** (`---@async`)."
    end
    out[#out + 1] = ""
    out[#out + 1] = io_sections(context, member, "**")
    local raises = raises_text(context, member)
    if raises then
      out[#out + 1] = ""
      out[#out + 1] = "**Errors raised**"
      out[#out + 1] = ""
      out[#out + 1] = raises
    end
  end
  return table.concat(out, "\n")
end

local function members_of_kind(class, kind)
  local list = {}
  for _, member in ipairs(class.members) do if member.kind == kind then list[#list + 1] = member end end
  return list
end

local function member_index(context, class, members)
  local out = { "| Name | Summary |", "|---|---|" }
  for _, member in ipairs(members) do
    local target = member.kind == "function" and context.targets[class.name .. "." .. member.name] or nil
    local label = "`" .. member.name .. "`"
    local text
    if target then
      text = link(context, class.name .. "." .. member.name, label)
    else
      text = ("[%s](#%s)"):format(label, member.name)
    end
    out[#out + 1] = ("| %s | %s |"):format(text, cell(member.summary ~= "" and link_prose(context, member.summary) or "-"))
  end
  return table.concat(out, "\n")
end

--- Class, type and submodule pages, and the page of the module of a package.
local function render_class(context, options, class, classes_of_package, errors_of_package)
  local body = {}
  local function add(...) for _, text in ipairs({ ... }) do body[#body + 1] = text; body[#body + 1] = "" end end
  add(summary_block(context, class))
  local fields, methods, functions = members_of_kind(class, "field"), members_of_kind(class, "method"),
    members_of_kind(class, "function")
  local init
  for _, member in ipairs(methods) do if member.name == "init" then init = member end end

  -- 2. Syntax
  local syntax = {}
  if class.is_root then
    syntax[#syntax + 1] = ("local %s = require(\"%s\")"):format(alias_of(class), class.name)
  else
    local header = "---@class " .. class.name
    if #class.extends > 0 then header = header .. " : " .. table.concat(class.extends, ", ") end
    syntax[#syntax + 1] = header
    for _, field in ipairs(fields) do
      syntax[#syntax + 1] = ("---@field %s %s"):format(field.name, field.type or "any")
    end
    if class.kind == "Class" then
      local params = init and parameter_names(init, true) or ""
      syntax[#syntax + 1] = ("local %s = %s(%s)"):format(class.short:lower(), class.short, params)
    end
  end
  for _, member in ipairs(methods) do
    if member.name ~= "init" then syntax[#syntax + 1] = member_signature(class, member) end
  end
  for _, member in ipairs(functions) do syntax[#syntax + 1] = member_signature(class, member) end
  add("## Syntax", "```lua\n" .. table.concat(syntax, "\n") .. "\n```")

  -- 3. Parameters and return values: the constructor, then the members.
  local part = {}
  if class.is_root then
    local subjects = {}
    for _, other in ipairs(classes_of_package) do
      if other ~= class then subjects[#subjects + 1] = other end
    end
    if #functions > 0 then
      part[#part + 1] = "### Functions\n\n" .. member_index(context, class, functions)
    end
    local type_rows = { "| Name | Kind | Summary |", "|---|---|---|" }
    for _, other in ipairs(subjects) do
      type_rows[#type_rows + 1] = ("| %s | %s | %s |"):format(link(context, other.name), other.kind,
        cell(other.summary ~= "" and link_prose(context, other.summary) or "-"))
    end
    if #subjects > 0 then part[#part + 1] = "### Classes and types\n\n" .. table.concat(type_rows, "\n") end
    local plain_fields = {}
    for _, field in ipairs(fields) do
      if not context.targets[field.type or ""] then plain_fields[#plain_fields + 1] = field end
    end
    if #plain_fields > 0 then
      local rows = { "| Name | Type | Description |", "|---|---|---|" }
      for _, field in ipairs(plain_fields) do
        rows[#rows + 1] = ("| `%s` | %s | %s |"):format(field.name, type_cell(context, field.type or "any"),
          cell(field.summary ~= "" and link_prose(context, field.summary) or "-"))
      end
      part[#part + 1] = "### Fields\n\n" .. table.concat(rows, "\n")
    end
  else
    if init then
      local constructor = io_sections(context, init, "**"):gsub("%*%*Return values%*%*.*$", ""):gsub("\n+$", "")
      part[#part + 1] = "### Constructor\n\n" .. constructor
    end
    if #fields > 0 then
      local items = {}
      for _, field in ipairs(fields) do items[#items + 1] = render_member(context, class, field) end
      part[#part + 1] = "### Fields\n\n" .. table.concat(items, "\n\n")
    end
    local callable = {}
    for _, member in ipairs(methods) do if member.name ~= "init" then callable[#callable + 1] = member end end
    for _, member in ipairs(functions) do callable[#callable + 1] = member end
    if #callable > 0 then
      local items = {}
      for _, member in ipairs(callable) do items[#items + 1] = render_member(context, class, member) end
      part[#part + 1] = (#methods > 1 and "### Methods\n\n" or "### Members\n\n") .. table.concat(items, "\n\n")
    end
  end
  add("## Parameters and return values", #part > 0 and table.concat(part, "\n\n") or "None.")

  -- 4. Errors raised
  local errors_out = {}
  if class.is_root then
    for _, other in ipairs(errors_of_package) do
      errors_out[#errors_out + 1] = ("- %s: %s"):format(link(context, other.name),
        one_line(other.summary ~= "" and link_prose(context, other.summary) or "no description yet"))
    end
    for _, text in ipairs(class.raises) do errors_out[#errors_out + 1] = link_prose(context, text) end
  else
    for _, text in ipairs(class.raises) do errors_out[#errors_out + 1] = link_prose(context, text) end
    local callable = {}
    for _, member in ipairs(methods) do callable[#callable + 1] = member end
    for _, member in ipairs(functions) do callable[#callable + 1] = member end
    for _, member in ipairs(callable) do
      if #member.raises > 0 then
        errors_out[#errors_out + 1] = ("**`%s`**: %s"):format(member.name,
          one_line(link_prose(context, table.concat(member.raises, " "))))
      end
    end
  end
  add("## Errors raised", #errors_out > 0 and table.concat(errors_out, class.is_root and "\n" or "\n\n")
    or "None documented.")

  -- 5. May suspend
  local suspending = {}
  for _, member in ipairs(class.members) do
    if member.async then
      suspending[#suspending + 1] = ("- [`%s`](#%s)"):format(
        (member.kind == "method" and (alias_of(class) .. ":") or (alias_of(class) .. ".")) .. member.name, member.name)
    end
  end
  if #suspending > 0 then
    local rows = {}
    for _, member in ipairs(class.members) do
      if member.async then
        local target = member.kind == "function" and context.targets[class.name .. "." .. member.name]
        local label = (member.kind == "method" and (alias_of(class) .. ":") or (alias_of(class) .. ".")) .. member.name
        rows[#rows + 1] = "- " .. (target and link(context, class.name .. "." .. member.name, "`" .. label .. "`")
          or ("[`%s`](#%s)"):format(label, member.name))
      end
    end
    add("## May suspend", "These members may suspend the running coroutine (`---@async`); call them from a "
      .. "coroutine managed by the reactor.\n\n" .. table.concat(rows, "\n"))
  else
    add("## May suspend", "No member suspends.")
  end

  -- 6-9
  add("## Examples", example_section(options, class.name))
  add("## Specifications and standards", standards_text(context, class))
  add("## Compatibility", compatibility_text(options, class))
  local extra = {}
  for _, parent in ipairs(class.extends) do extra[#extra + 1] = parent end
  if not class.is_root then extra[#extra + 1] = "hecate." .. class.package_name end
  add("## See also", see_entries(context, class, extra))

  local title = class.is_root and class.name or class.short
  local meta = {
    title = title,
    description = plain(class.summary ~= "" and class.summary or (class.name .. ".")),
    order = class.is_root and options.order_of and options.order_of[class.package_name] or nil,
    source = source_of(class.package_name, class.file),
  }
  return page(meta, class.package_name, class.name, body)
end

--- Generates the reference pages of one or more packages.
---
--- Raises `hecate.core.ArgumentError` if `inputs` is not a list of `{ name, export }`.
---@param inputs hecate.doc.ReferenceInput[]
---@param options? hecate.doc.ReferenceOptions
---@return hecate.doc.ReferenceResult
function M.generate(inputs, options)
  options = options or {}
  if type(inputs) ~= "table" then
    error(core.ArgumentError("generate expects a list of { name, export } inputs"), 2)
  end
  local root = options.root or "reference"
  local problems = {}
  local order_of = {}
  for index, input in ipairs(inputs) do
    if type(input) ~= "table" or type(input.name) ~= "string" or input.export == nil then
      error(core.ArgumentError(("generate: input %d must be { name = string, export = ... }"):format(index)), 2)
    end
    order_of[input.name] = index * 10
  end
  local settings = { order_of = order_of, since = options.since, examples = options.examples }
  options = settings

  local classes, by_name = build_classes(inputs, root, problems)

  -- Targets: every symbol that has a page or an anchor.
  local targets = {}
  local seen_paths = {}
  local function claim(path, owner)
    local key = path:lower()
    if seen_paths[key] then
      problems[#problems + 1] = ("%s and %s would write the same page %s"):format(seen_paths[key], owner, path)
      return false
    end
    seen_paths[key] = owner
    return true
  end
  local function_pages = {}
  for _, class in ipairs(classes) do
    if claim(class.path, class.name) then targets[class.name] = class.path end
    for _, member in ipairs(class.members) do
      if member.kind == "function" and class.is_root then
        local path = ("%s/%s/functions/%s.md"):format(root, class.package_name, member.name)
        if claim(path, class.name .. "." .. member.name) then
          targets[class.name .. "." .. member.name] = path
          function_pages[#function_pages + 1] = { class = class, member = member, path = path }
        end
      elseif not (class.is_root and member.kind == "field") then
        -- The fields of the module page are rows of a table: they have no heading, so no anchor.
        targets[class.name .. (member.kind == "method" and ":" or ".") .. member.name] = class.path .. "#" .. member.name
      end
    end
  end

  local pages, order = {}, {}
  local function emit(path, content)
    pages[path] = content
    order[#order + 1] = path
  end
  local by_package = {}
  for _, class in ipairs(classes) do
    by_package[class.package_name] = by_package[class.package_name] or { classes = {}, errors = {} }
    local entry = by_package[class.package_name]
    entry.classes[#entry.classes + 1] = class
    if class.kind == "Error class" then entry.errors[#entry.errors + 1] = class end
  end
  for _, class in ipairs(classes) do
    local entry = by_package[class.package_name]
    local context = { targets = targets, page = class.path }
    emit(class.path, render_class(context, options, class, entry.classes, entry.errors))
  end
  for _, item in ipairs(function_pages) do
    local context = { targets = targets, page = item.path }
    emit(item.path, render_function(context, options, item.class, item.member))
  end
  table.sort(order)
  return { pages = pages, problems = problems, order = order }
end

--- Names of the generated pages of a package directory, for the stale-page check of writers.
---@param content string
---@return boolean
function M.is_generated(content)
  return content:find("Generated by hecate.doc from the LuaLS export", 1, true) ~= nil
end

return M
