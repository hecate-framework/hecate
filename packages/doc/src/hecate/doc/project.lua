-- Project documentation: the pages `hecate doc build` generates for a user project from its
-- contract (OpenAPI document) and its configuration schema, and the build that joins them with
-- the guides of the project (documentation.md, "Project documentation generated for users").
-- The page generators are pure: tables in, Markdown out, deterministic. Every piece of text
-- that comes from the contract is escaped, because the contract is data of the project, not
-- Markdown.
global <const> require, type, ipairs, pairs, next, table, string, error, tostring, math

local core = require("hecate.core")
local html = require("hecate.doc.internal.html")
local build = require("hecate.doc.build")
local errors = require("hecate.doc.errors")
local page_id = require("hecate.doc.internal.page_id")

--- Pages generated from a project's contract and configuration.
---@class hecate.doc.project
local M = {}

--- The notice written at the top of every generated project page.
M.GENERATED = "<!-- Generated by hecate.doc from the contract and the configuration schema of the project. "
  .. "Do not edit: change the project and build again. -->"

--- True for a page written by this module.
---@param text any  anything is accepted: a value that is not a string is not generated
---@return boolean
function M.is_generated(text)
  return type(text) == "string" and text:find(M.GENERATED, 1, true) ~= nil
end

local METHODS = { "get", "put", "post", "delete", "options", "head", "patch", "trace" }

-- Limits for contracts that are data of the project and may be hostile or enormous.
local MAX_ROWS = 500       -- property rows of one table
local MAX_DEPTH = 6        -- nesting of object properties
local MAX_TYPE_DEPTH = 8   -- nesting of the type expression of a cell
local MAX_VALUES = 50      -- values of an enumeration shown
local MAX_SERIALISED_DEPTH = 8

local function list(value) return type(value) == "table" and value or {} end

-- Escapes text for a paragraph or a table cell: one line, no Markdown syntax, no raw HTML, nothing that
-- starts a block at the beginning of the line (CommonMark 0.31.2, 4.1 thematic breaks, 4.3 setext
-- underlines, 5.2 list items) and no character reference (2.5).
local function plain(text)
  text = tostring(text or ""):gsub("%s*[\r\n]+%s*", " ")
  text = text:gsub("^%s+", ""):gsub("%s+$", "")
  text = text:gsub("([\\`*_{}%[%]<>|#~&])", "\\%1")
  text = text:gsub("^([%-+=])", "\\%1")
  text = text:gsub("^(%d+)([.)])", "%1\\%2")
  return text
end

-- An inline code span (CommonMark 6.1). In a table cell a pipe is escaped even inside the span
-- (GFM 4.10); elsewhere it is literal.
local function code(text, in_cell)
  text = tostring(text):gsub("%c+", " ")
  if text == "" then return "" end
  local ticks = "`"
  while text:find(ticks, 1, true) do ticks = ticks .. "`" end
  if in_cell then text = text:gsub("|", "\\|") end
  local pad = (text:find("^`") or text:find("`$")) and " " or ""
  return ticks .. pad .. text .. pad .. ticks
end

local function sorted_keys(map)
  local keys = {}
  for key in pairs(list(map)) do
    if type(key) == "string" or type(key) == "number" then keys[#keys + 1] = key end
  end
  table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
  return keys
end

-- JSON-like text with sorted keys: the same value is always rendered the same way.
local function serialise(value, depth)
  depth = depth or 0
  local kind = type(value)
  if kind == "string" then
    return '"' .. value:gsub('[%c"\\]', function(char)
      local named = { ['"'] = '\\"', ["\\"] = "\\\\", ["\n"] = "\\n", ["\t"] = "\\t", ["\r"] = "\\r" }
      return named[char] or ("\\u%04x"):format(char:byte())
    end) .. '"'
  elseif kind == "number" or kind == "boolean" or kind == "nil" then
    return tostring(value)
  elseif kind ~= "table" then
    return '"<' .. kind .. '>"'
  end
  if depth >= MAX_SERIALISED_DEPTH then return "..." end
  local parts = {}
  if #value > 0 or next(value) == nil then
    for _, item in ipairs(value) do parts[#parts + 1] = serialise(item, depth + 1) end
    return "[" .. table.concat(parts, ",") .. "]"
  end
  for _, key in ipairs(sorted_keys(value)) do
    parts[#parts + 1] = serialise(tostring(key)) .. ":" .. serialise(value[key], depth + 1)
  end
  return "{" .. table.concat(parts, ",") .. "}"
end

-- The text of a default or an enumeration member: a string as it is, any other value serialised.
local function value_text(value)
  if type(value) == "string" then return value end
  return serialise(value)
end

local function unescape_pointer(name)
  return (name:gsub("~1", "/"):gsub("~0", "~"))
end

-- Follows `$ref` chains into `#/components/<section>/<name>` (OpenAPI 3.1.0, 4.8.17 Reference Object) or,
-- for a schema, `#/$defs/<name>` of the document itself (JSON Schema 2020-12, 8.2.4). Returns the target and the
-- list of references crossed; an unresolvable reference is returned as it is.
local function resolve_in(document, node, section)
  local crossed = {}
  while type(node) == "table" and type(node["$ref"]) == "string" and #crossed < 16 do
    local ref = node["$ref"]
    local name = ref:match("^#/components/" .. section .. "/(.+)$")
    local target
    if name then
      local components = type(document.components) == "table" and document.components[section]
      target = type(components) == "table" and components[unescape_pointer(name)]
    elseif section == "schemas" then
      name = ref:match("^#/%$defs/(.+)$")
      target = name and type(document["$defs"]) == "table" and document["$defs"][unescape_pointer(name)]
    end
    crossed[#crossed + 1] = ref
    if type(target) ~= "table" then return node, crossed end
    node = target
  end
  return node, crossed
end

local function resolve(document, schema) return resolve_in(document, schema, "schemas") end

local function type_of(document, schema, depth)
  depth = depth or 0
  if type(schema) ~= "table" or depth > MAX_TYPE_DEPTH then return "any" end
  local ref = schema["$ref"]
  if type(ref) == "string" then return ref:match("([^/]+)$") or "any" end
  local kind = schema.type
  if type(kind) == "table" then
    local names = {}
    for _, name in ipairs(kind) do
      if type(name) == "string" then names[#names + 1] = name end
    end
    kind = #names > 0 and table.concat(names, " or ") or nil
  elseif type(kind) ~= "string" then
    kind = nil
  end
  if kind == "array" then return "array of " .. type_of(document, schema.items, depth + 1) end
  return kind or (schema.enum and "enum") or "any"
end

local function constraints(schema)
  local parts = {}
  if type(schema) ~= "table" then return "" end
  if type(schema.enum) == "table" then
    local values = {}
    for index, value in ipairs(schema.enum) do
      if index > MAX_VALUES then values[#values + 1] = "..."; break end
      values[#values + 1] = code(value_text(value), true)
    end
    parts[#parts + 1] = "one of " .. table.concat(values, ", ")
  end
  if schema.const ~= nil then parts[#parts + 1] = "always " .. code(value_text(schema.const), true) end
  if schema.minimum ~= nil and schema.maximum ~= nil then
    parts[#parts + 1] = ("%s to %s"):format(tostring(schema.minimum), tostring(schema.maximum))
  elseif schema.minimum ~= nil then
    parts[#parts + 1] = "at least " .. tostring(schema.minimum)
  elseif schema.maximum ~= nil then
    parts[#parts + 1] = "at most " .. tostring(schema.maximum)
  end
  if schema.minLength ~= nil then parts[#parts + 1] = "length at least " .. tostring(schema.minLength) end
  if schema.maxLength ~= nil then parts[#parts + 1] = "length at most " .. tostring(schema.maxLength) end
  if schema.pattern ~= nil then parts[#parts + 1] = "pattern " .. code(value_text(schema.pattern), true) end
  if schema.format ~= nil then parts[#parts + 1] = "format " .. code(value_text(schema.format), true) end
  return table.concat(parts, "; ")
end

-- Property rows of an object schema, nested objects flattened with dotted paths. `state` bounds the work on an
-- untrusted contract: `rows` is capped (`truncated` is set), a reference already being expanded on the
-- current path is shown as a row and not expanded again, and the nesting is limited.
local function property_rows(document, schema, prefix, state, depth, visiting)
  local target, crossed = resolve(document, schema)
  if type(target) ~= "table" or type(target.properties) ~= "table" or depth > MAX_DEPTH then return end
  for _, ref in ipairs(crossed) do
    if visiting[ref] then return end
  end
  for _, ref in ipairs(crossed) do visiting[ref] = true end
  local required = {}
  for _, name in ipairs(list(target.required)) do required[name] = true end
  for _, name in ipairs(sorted_keys(target.properties)) do
    if #state.rows >= MAX_ROWS then state.truncated = true; break end
    local property = target.properties[name]
    local path = prefix .. tostring(name)
    local resolved, property_refs = resolve(document, property)
    local nested = type(resolved) == "table" and type(resolved.properties) == "table" and depth < MAX_DEPTH
    for _, ref in ipairs(property_refs) do
      if visiting[ref] then nested = false end
    end
    if nested then
      property_rows(document, property, path .. ".", state, depth + 1, visiting)
    else
      state.rows[#state.rows + 1] = {
        path = path, type = type_of(document, property), required = required[name] == true,
        default = type(resolved) == "table" and resolved.default,
        constraints = constraints(resolved),
        description = type(property) == "table" and (property.description or (type(resolved) == "table" and resolved.description)) or nil,
      }
    end
  end
  for _, ref in ipairs(crossed) do visiting[ref] = nil end
end

local function rows_of(document, schema)
  local state = { rows = {} }
  property_rows(document, schema, "", state, 0, {})
  return state
end

local function table_of_properties(lines, state, with_default)
  lines[#lines + 1] = with_default and "| Key | Type | Required | Default | Constraints | Description |"
    or "| Name | Type | Required | Constraints | Description |"
  lines[#lines + 1] = with_default and "|---|---|---|---|---|---|" or "|---|---|---|---|---|"
  for _, row in ipairs(state.rows) do
    local cells = { code(row.path, true), plain(row.type), row.required and "required" or "optional" }
    if with_default then cells[#cells + 1] = row.default ~= nil and code(value_text(row.default), true) or "" end
    cells[#cells + 1] = row.constraints
    cells[#cells + 1] = plain(row.description or "")
    lines[#lines + 1] = "| " .. table.concat(cells, " | ") .. " |"
  end
  lines[#lines + 1] = ""
  if state.truncated then
    lines[#lines + 1] = ("The list is truncated: only the first %d properties are shown."):format(MAX_ROWS)
    lines[#lines + 1] = ""
  end
end

-- A YAML double-quoted scalar (YAML 1.2.2, 7.3.1) on one line. Control characters become a space: the
-- front matter parser of this package accepts only the escapes `\\`, `\"`, `\n` and `\t`.
local function yaml_quote(text)
  text = tostring(text):gsub("%c", " "):gsub("\\", "\\\\"):gsub('"', '\\"')
  return '"' .. text .. '"'
end

local function front(title, description, order)
  return { "---", "description: " .. yaml_quote(description or title),
    "order: " .. tostring(order), "---", "", M.GENERATED, "", "# " .. plain(title), "" }
end

-- Operations of a document, sorted by path then method.
local function operations_of(document)
  local operations = {}
  for _, path in ipairs(sorted_keys(document.paths)) do
    local item = document.paths[path]
    if type(item) == "table" then
      for _, method in ipairs(METHODS) do
        local operation = item[method]
        if type(operation) == "table" then
          operations[#operations + 1] = { path = path, method = method:upper(), operation = operation, parameters = item.parameters }
        end
      end
    end
  end
  return operations
end

local function operation_title(entry)
  local id = entry.operation.operationId
  return type(id) == "string" and id ~= "" and id or (entry.method .. " " .. entry.path)
end

-- The parameters of an operation: those of the path item, then those of the operation, an operation
-- parameter replacing a path-level one with the same name and location (OpenAPI 3.1.0, 4.8.9).
local function parameters_of(document, entry)
  local merged, order = {}, {}
  for _, group in ipairs({ list(entry.parameters), list(entry.operation.parameters) }) do
    for _, raw in ipairs(group) do
      local parameter = resolve_in(document, raw, "parameters")
      if type(parameter) == "table" then
        local key = tostring(parameter.name) .. "\0" .. tostring(parameter["in"])
        if merged[key] == nil then order[#order + 1] = key end
        merged[key] = parameter
      end
    end
  end
  local out = {}
  for _, key in ipairs(order) do out[#out + 1] = merged[key] end
  return out
end

local function operation_section(document, entry, title, lines)
  local operation = entry.operation
  lines[#lines + 1] = "## " .. plain(title)
  lines[#lines + 1] = ""
  if operation.deprecated then lines[#lines + 1] = "> [!WARNING]\n> Deprecated."; lines[#lines + 1] = "" end
  lines[#lines + 1] = code(entry.method .. " " .. entry.path)
  lines[#lines + 1] = ""
  if operation.summary then lines[#lines + 1] = plain(operation.summary); lines[#lines + 1] = "" end
  if operation.description then lines[#lines + 1] = plain(operation.description); lines[#lines + 1] = "" end
  local parameters = parameters_of(document, entry)
  if #parameters > 0 then
    lines[#lines + 1] = "### Parameters"
    lines[#lines + 1] = ""
    lines[#lines + 1] = "| Name | In | Type | Required | Constraints | Description |"
    lines[#lines + 1] = "|---|---|---|---|---|---|"
    for _, parameter in ipairs(parameters) do
      local schema = resolve(document, parameter.schema)
      lines[#lines + 1] = ("| %s | %s | %s | %s | %s | %s |"):format(code(parameter.name or "", true),
        plain(parameter["in"]), plain(type_of(document, parameter.schema)),
        parameter.required and "required" or "optional", constraints(schema), plain(parameter.description))
    end
    lines[#lines + 1] = ""
  end
  local body = resolve_in(document, operation.requestBody, "requestBodies")
  if type(body) == "table" then
    lines[#lines + 1] = "### Request body"
    lines[#lines + 1] = ""
    lines[#lines + 1] = body.required and "Required." or "Optional."
    lines[#lines + 1] = ""
    for _, media in ipairs(sorted_keys(body.content)) do
      local content = type(body.content[media]) == "table" and body.content[media] or {}
      lines[#lines + 1] = code(media) .. " of " .. plain(type_of(document, content.schema))
      lines[#lines + 1] = ""
      local state = rows_of(document, content.schema)
      if #state.rows > 0 then table_of_properties(lines, state, false) end
    end
  end
  lines[#lines + 1] = "### Responses"
  lines[#lines + 1] = ""
  for _, status in ipairs(sorted_keys(operation.responses)) do
    local response = resolve_in(document, operation.responses[status], "responses")
    if type(response) == "table" then
      lines[#lines + 1] = ("- %s: %s"):format(code(status), plain(response.description))
      for _, media in ipairs(sorted_keys(response.content)) do
        local content = type(response.content[media]) == "table" and response.content[media] or {}
        lines[#lines + 1] = ("  - %s of %s"):format(code(media), plain(type_of(document, content.schema)))
      end
    end
  end
  lines[#lines + 1] = ""
end

-- The file of each tag below `api/`: the slug of the tag, never `index` (the route table), never a
-- device name of Windows, and unique (a duplicate gets `-2`, `-3`, ...; the order of the tags is fixed).
local function tag_files(tag_order)
  local used, files = { index = true }, {}
  for _, tag in ipairs(tag_order) do
    local name = html.slug(tag)
    if name == "untagged" then name = "untagged-operations" end
    if page_id.windows_problem(name) then name = name .. "-tag" end
    local candidate, number = name, 2
    while used[candidate] do
      candidate = name .. "-" .. number
      number = number + 1
    end
    used[candidate] = true
    files[tag] = candidate
  end
  return files
end

-- A heading of an operation, unique among the headings of its page: the renderer derives the anchor from the
-- title and numbers duplicates itself, so the title is made unique here, and the index links to it.
local function unique_title(title, used)
  local function reserved(slug)
    for _, name in ipairs({ "parameters", "request-body", "responses" }) do
      if slug == name or slug:find("^" .. name:gsub("%-", "%%-") .. "%-%d+$") then return true end
    end
    return false
  end
  -- A title that is (or numbers like) a fixed heading of the page cannot be numbered into uniqueness.
  local base = reserved(html.slug(title)) and (title .. " operation") or title
  local candidate, number = base, 2
  while used[html.slug(candidate)] or reserved(html.slug(candidate)) do
    candidate = ("%s (%d)"):format(base, number)
    number = number + 1
  end
  used[html.slug(candidate)] = true
  return candidate
end

--- Generates the API reference and the route table from an OpenAPI 3.1 document table: an index
--- page (`api/index.md`, with the table of every route) and one page per tag
--- (`api/<tag>.md`; operations without a tag go to `api/untagged-operations.md`).
--- The reference is static HTML, with no interactive console (OQ-141).
---@param document table  the OpenAPI document (`hecate.openapi.build` result, or decoded JSON)
---@return table<string, string> pages  path below the locale root to Markdown
function M.api_pages(document)
  if type(document) ~= "table" or type(document.paths) ~= "table" then
    error(core.ArgumentError("doc.project.api_pages: expects an OpenAPI document with `paths`"), 2)
  end
  local operations = operations_of(document)
  local by_tag, tag_order, descriptions = {}, {}, {}
  for _, tag in ipairs(list(document.tags)) do
    if type(tag) == "table" and type(tag.name) == "string" and not by_tag[tag.name] then
      tag_order[#tag_order + 1] = tag.name
      descriptions[tag.name] = tag.description
      by_tag[tag.name] = {}
    end
  end
  local extra = {}
  for _, entry in ipairs(operations) do
    local first = type(entry.operation.tags) == "table" and entry.operation.tags[1]
    local tag = type(first) == "string" and first or "Untagged operations"
    entry.tag = tag
    if not by_tag[tag] then by_tag[tag] = {}; extra[#extra + 1] = tag end
    table.insert(by_tag[tag], entry)
  end
  table.sort(extra)
  for _, tag in ipairs(extra) do tag_order[#tag_order + 1] = tag end
  local files = tag_files(tag_order)

  -- Titles and anchors, per page.
  for _, tag in ipairs(tag_order) do
    local used = { [html.slug(tag)] = true, parameters = true, ["request-body"] = true, responses = true }
    for _, entry in ipairs(by_tag[tag]) do entry.title = unique_title(operation_title(entry), used) end
  end

  local info = type(document.info) == "table" and document.info or {}
  local pages = {}
  local index = front(info.title and (tostring(info.title) .. " API") or "API reference", info.summary or info.description, 1)
  if info.version then index[#index + 1] = "Version " .. code(info.version) .. "."; index[#index + 1] = "" end
  if info.description then index[#index + 1] = plain(info.description); index[#index + 1] = "" end
  index[#index + 1] = "## Routes"
  index[#index + 1] = ""
  index[#index + 1] = "| Method | Path | Operation | Summary |"
  index[#index + 1] = "|---|---|---|---|"
  for _, entry in ipairs(operations) do
    index[#index + 1] = ("| %s | %s | [%s](%s.md#%s) | %s |"):format(code(entry.method, true), code(entry.path, true),
      plain(entry.title), files[entry.tag], html.slug(entry.title), plain(entry.operation.summary))
  end
  index[#index + 1] = ""
  for position, tag in ipairs(tag_order) do
    local lines = front(tag, descriptions[tag] or ("Operations tagged " .. tag), position + 1)
    if descriptions[tag] then lines[#lines + 1] = plain(descriptions[tag]); lines[#lines + 1] = "" end
    for _, entry in ipairs(by_tag[tag]) do operation_section(document, entry, entry.title, lines) end
    pages["api/" .. files[tag] .. ".md"] = table.concat(lines, "\n")
  end
  pages["api/index.md"] = table.concat(index, "\n")
  return pages
end

--- Generates the configuration reference (`configuration.md`) from the JSON Schema of the
--- configuration: one row per key, nested objects flattened with dotted paths (`$ref` into the
--- `$defs` of the schema are followed).
---@param schema table  JSON Schema 2020-12 table (`schema:emit()` of the configuration schema)
---@return string markdown
function M.configuration_page(schema)
  if type(schema) ~= "table" then
    error(core.ArgumentError("doc.project.configuration_page: expects a JSON Schema table"), 2)
  end
  local lines = front("Configuration", schema.description or "Configuration keys, their types and defaults.", 50)
  local state = rows_of(schema, schema)
  if #state.rows == 0 then
    lines[#lines + 1] = "The configuration declares no keys."
  else
    table_of_properties(lines, state, true)
  end
  return table.concat(lines, "\n")
end

local LUA_KEYWORDS = {}
for word in ("and break do else elseif end false for function global goto if in local nil not or repeat return then true until while")
  :gmatch("%a+") do LUA_KEYWORDS[word] = true end

-- The Lua type literal of a scalar, or nil for what cannot be one (a table, a number that is not finite).
local function literal(value)
  local kind = type(value)
  if kind == "string" then return (string.format("%q", value):gsub("\\\n", "\\n")) end
  if kind == "boolean" then return tostring(value) end
  if kind == "number" and value == value and value ~= math.huge and value ~= -math.huge then return tostring(value) end
  return nil
end

local MAX_LUA_TYPE_DEPTH = 16

local function lua_type(schema, namespace, depth)
  depth = depth or 0
  if type(schema) ~= "table" or depth > MAX_LUA_TYPE_DEPTH then return "any" end
  local ref = schema["$ref"]
  if type(ref) == "string" then
    local name = ref:match("([^/]+)$")
    return name and name:match("^[%a_][%w_]*$") and (namespace .. "." .. name) or "any"
  end
  if schema.const ~= nil then return literal(schema.const) or "any" end
  if type(schema.enum) == "table" then
    local values = {}
    for _, value in ipairs(schema.enum) do
      local text = literal(value)
      if not text then return "any" end
      values[#values + 1] = text
    end
    return #values > 0 and table.concat(values, "|") or "any"
  end
  local alternatives = type(schema.anyOf) == "table" and schema.anyOf or type(schema.oneOf) == "table" and schema.oneOf
  if alternatives then
    local parts = {}
    for _, alternative in ipairs(alternatives) do parts[#parts + 1] = lua_type(alternative, namespace, depth + 1) end
    return #parts > 0 and table.concat(parts, "|") or "any"
  end
  if type(schema.allOf) == "table" then
    return #schema.allOf == 1 and lua_type(schema.allOf[1], namespace, depth + 1) or "any"
  end
  local kind = schema.type
  if type(kind) == "table" then
    local parts = {}
    for _, name in ipairs(kind) do
      parts[#parts + 1] = lua_type({ type = name, items = schema.items, properties = schema.properties,
        additionalProperties = schema.additionalProperties }, namespace, depth + 1)
    end
    return #parts > 0 and table.concat(parts, "|") or "any"
  end
  if kind == "string" then return "string" end
  if kind == "integer" then return "integer" end
  if kind == "number" then return "number" end
  if kind == "boolean" then return "boolean" end
  if kind == "null" then return "nil" end
  if kind == "array" then
    local item = lua_type(schema.items, namespace, depth + 1)
    return (item:find("|", 1, true) and "(" .. item .. ")" or item) .. "[]"
  end
  if kind == "object" then
    local additional = schema.additionalProperties
    if type(additional) == "table" and not schema.properties then
      return "table<string, " .. lua_type(additional, namespace, depth + 1) .. ">"
    end
    return "table"
  end
  return "any"
end

local function one_line(text)
  return (tostring(text):gsub("%s*[\r\n]+%s*", " "))
end

--- Generates a LuaLS `---@meta` file for the named schemas of a project (`schema:emit()` results
--- keyed by name, or the `$defs` of one): an object schema becomes a `---@class` with one
--- `---@field` per property, an enumeration an `---@alias`. Names are qualified by `namespace`
--- (`<namespace>.<name>`), so that a `$ref` resolves. Deterministic: names and properties are sorted.
---@param schemas table<string, table>  JSON Schema 2020-12 tables by name
---@param namespace string  Lua module name the types live in (e.g. `shop.schemas`)
---@return string meta  Lua source of the declaration file
function M.meta(schemas, namespace)
  local function valid_namespace()
    if type(namespace) ~= "string" then return false end
    for segment in (namespace .. "."):gmatch("([^.]*)%.") do
      if not segment:match("^[%a_][%w_]*$") then return false end
    end
    return true
  end
  if type(schemas) ~= "table" or not valid_namespace() then
    error(core.ArgumentError("doc.project.meta: expects named schemas and a namespace such as `shop.schemas`"), 2)
  end
  for name in pairs(schemas) do
    if type(name) ~= "string" then
      error(core.ArgumentError("doc.project.meta: the schemas must be keyed by name (a string)"), 2)
    end
  end
  local lines = { "---@meta " .. namespace, "-- Generated by hecate.doc from the schemas of the project. Do not edit.", "" }
  for _, name in ipairs(sorted_keys(schemas)) do
    if not name:match("^[%a_][%w_]*$") or LUA_KEYWORDS[name] then
      error(core.ArgumentError(("doc.project.meta: the schema name %q is not a Lua identifier"):format(name)), 2)
    end
    local schema = schemas[name]
    local qualified = namespace .. "." .. name
    if type(schema) == "table" and type(schema.properties) == "table" then
      for key in pairs(schema.properties) do
        if type(key) ~= "string" then
          error(core.ArgumentError(("doc.project.meta: the properties of %s must be keyed by name (a string)"):format(name)), 2)
        end
      end
      if schema.description then lines[#lines + 1] = "--- " .. one_line(schema.description) end
      lines[#lines + 1] = "---@class " .. qualified
      local required = {}
      for _, key in ipairs(list(schema.required)) do required[key] = true end
      for _, key in ipairs(sorted_keys(schema.properties)) do
        local property = schema.properties[key]
        local field = key:match("^[%a_][%w_]*$") and not LUA_KEYWORDS[key] and key or ("[" .. literal(key) .. "]")
        local text = ("---@field %s%s %s"):format(field, required[key] and "" or "?", lua_type(property, namespace))
        if type(property) == "table" and property.description then
          text = text .. "  " .. one_line(property.description)
        end
        lines[#lines + 1] = text
      end
    else
      lines[#lines + 1] = ("---@alias %s %s"):format(qualified, lua_type(schema, namespace))
    end
    lines[#lines + 1] = ""
  end
  return table.concat(lines, "\n")
end

---@class hecate.doc.ProjectBuildOptions : hecate.doc.BuildOptions
---@field document? table  OpenAPI document: adds the API reference and the route table
---@field configuration? table  JSON Schema of the configuration: adds the configuration reference
---@field pages? table<string, string>  guides of the project, path below the locale root to Markdown (`.md`, relative, no `..`)
---@field code? { root: string, name: string, executable?: string, config?: string }  document the annotated sources `<root>/src` of the project as the code reference `reference/<name>/` (skipped with a problem when LuaLS is missing). LuaLS reads the `.luarc.json` of `root` (or `config`) and runs the plugin it declares: `root` must be trusted
---@field locale? string  locale directory the pages are written to (default the default locale, "en")

---@class hecate.doc.ProjectBuildReport : hecate.doc.BuildReport
---@field code? hecate.doc.ReferenceSiteReport  the code reference, when `code` was given

local function bad_option(field, expected)
  error(core.ArgumentError(("doc.project.build: option `%s` must be %s"):format(field, expected)), 3)
end

-- A page path given by the caller, normalised (`./` and `//` dropped), or nil and the reason.
local function normalise_page_path(path)
  if type(path) ~= "string" or path == "" then return nil, "a non-empty string" end
  if path:find("^/") or path:find("^%a:") then return nil, "relative (it is absolute)" end
  if path:find("\\", 1, true) then return nil, "free of backslashes" end
  local parts = {}
  for segment in path:gmatch("[^/]+") do
    if segment == ".." then return nil, "free of `..` segments" end
    if segment:sub(1, 1) == "." and segment ~= "." then return nil, "free of hidden segments (they are not part of a site)" end
    if segment ~= "." then parts[#parts + 1] = segment end
  end
  local normal = table.concat(parts, "/")
  if not normal:find("%.md$") or #parts == 0 then return nil, "a Markdown file name (`.md`)" end
  local problem = page_id.windows_problem(normal)
  if problem then return nil, "a portable file name: " .. problem end
  return normal
end

local function validate(options)
  if type(options) ~= "table" or type(options.fs) ~= "table" or type(options.source) ~= "string" then
    error(core.ArgumentError("doc.project.build: expects { config, source, out, fs }"), 3)
  end
  if options.source == "" then bad_option("source", "a non-empty string") end
  if options.config ~= nil and type(options.config) ~= "table" then bad_option("config", "a table") end
  if options.document ~= nil and type(options.document) ~= "table" then bad_option("document", "an OpenAPI document table") end
  if options.configuration ~= nil and type(options.configuration) ~= "table" then
    bad_option("configuration", "a JSON Schema table")
  end
  local locale = options.locale
  if locale == nil then locale = type(options.config) == "table" and options.config.default_locale or "en" end
  if type(locale) ~= "string" or not locale:match("^[%w%-]+$") then
    bad_option("locale", "a locale code made of letters, digits and `-`")
  end
  local pages = {}
  if options.pages ~= nil then
    if type(options.pages) ~= "table" then bad_option("pages", "a table of Markdown texts by path") end
    for path, text in pairs(options.pages) do
      local normal, reason = normalise_page_path(path)
      if not normal then bad_option("pages", ("keyed by page paths: %q is not %s"):format(tostring(path), reason)) end
      ---@cast normal string
      if type(text) ~= "string" then bad_option("pages", ("a table of strings: the value of %q is not a string"):format(path)) end
      if pages[normal] then bad_option("pages", ("keyed by distinct page paths: %q names the same page as another key"):format(path)) end
      pages[normal] = text
    end
  end
  local code = options.code
  if code ~= nil then
    if type(code) ~= "table" or type(code.root) ~= "string" or type(code.name) ~= "string"
      or not code.name:match("^[%w_][%w_.%-]*$") or code.name:find("..", 1, true) then
      bad_option("code", "{ root = string, name = a package name such as `shop` }")
    end
    for _, key in ipairs({ "executable", "config" }) do
      if code[key] ~= nil and type(code[key]) ~= "string" then bad_option("code." .. key, "a string") end
    end
  end
  return locale, pages
end

-- Generated files of the previous builds that this build no longer produces.
local function stale_files(fs, root, generated)
  local stale = {}
  local function visit(directory, relative)
    for _, entry in ipairs(fs:list(directory) or {}) do
      local child = relative == "" and entry.name or (relative .. "/" .. entry.name)
      if entry.is_directory then
        visit(directory .. "/" .. entry.name, child)
      elseif entry.name:find("%.md$") and not generated[child] and M.is_generated(fs:read(directory .. "/" .. entry.name)) then
        stale[#stale + 1] = child
      end
    end
  end
  visit(root .. "/api", "api")
  if fs:exists(root .. "/configuration.md") and not generated["configuration.md"]
    and M.is_generated(fs:read(root .. "/configuration.md")) then
    stale[#stale + 1] = "configuration.md"
  end
  table.sort(stale)
  return stale
end

--- Builds the site of a project. The pages (guides and generated) are written below
--- `<source>/<locale>/`, then `build` runs. Generated pages replace the previous ones, and the generated
--- pages that this build no longer produces are removed. Everything is checked before anything is written:
--- a guide that would overwrite a generated page, or a generated page that would overwrite a file that is
--- not generated, raises `hecate.doc.BuildError` and leaves the tree untouched. A wrong option raises
--- `core.ArgumentError` naming it.
---@param options hecate.doc.ProjectBuildOptions
---@return hecate.doc.ProjectBuildReport
function M.build(options)
  local locale, pages = validate(options)
  local fs = options.fs
  local root = options.source:gsub("/+$", "") .. "/" .. locale
  local generated = {}
  if options.document then
    for path, text in pairs(M.api_pages(options.document)) do generated[path] = text end
  end
  if options.configuration then generated["configuration.md"] = M.configuration_page(options.configuration) end
  -- On a case-insensitive file system two paths that differ only by case are one file.
  local folded = {}
  for path in pairs(generated) do folded[path:lower()] = path end
  for _, path in ipairs(sorted_keys(pages)) do
    if folded[path:lower()] then
      error(errors.BuildError({
        message = ("doc.project.build: the page %s is generated; remove the guide or rename it"):format(path),
        context = { path = path },
      }), 0)
    end
  end
  for _, path in ipairs(sorted_keys(generated)) do
    local target = root .. "/" .. path
    if fs:exists(target) and not M.is_generated(fs:read(target)) then
      error(errors.BuildError({
        message = ("doc.project.build: %s exists and is not generated; move it, or rename the generated page"):format(target),
        context = { path = target },
      }), 0)
    end
  end
  for _, path in ipairs(stale_files(fs, root, generated)) do fs:remove_tree(root .. "/" .. path) end
  for _, path in ipairs(sorted_keys(pages)) do fs:write(root .. "/" .. path, pages[path]) end
  for _, path in ipairs(sorted_keys(generated)) do fs:write(root .. "/" .. path, generated[path]) end
  local code_report
  if options.code then
    code_report = require("hecate.doc.reference_site").run({
      root = options.code.root, packages = { options.code.name }, layout = "src", out = root,
      fs = fs, executable = options.code.executable, config = options.code.config,
    })
  end
  local report = build.build(options) --[[@as hecate.doc.ProjectBuildReport]]
  if code_report then
    report.code = code_report
    for _, problem in ipairs(code_report.problems) do report.problems[#report.problems + 1] = problem end
    if code_report.skipped then report.problems[#report.problems + 1] = code_report.skipped end
  end
  return report
end

return M
