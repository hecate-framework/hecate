-- Page identifiers as file names: portability to Windows and Unicode normalisation.
--
-- A site is built from a tree authored elsewhere, and its page ids become directory names of the
-- output, so an id must be one valid file name on every platform. `windows_problem` applies the naming
-- rules of Windows (Microsoft, "Naming Files, Paths, and Namespaces": reserved characters, reserved
-- device names also with an extension, no trailing dot or space).
--
-- `nfc` composes the Latin letters that have a canonical decomposition (Unicode Standard, 3.11 and
-- UAX #15, canonical composition) so that "e" + U+0301 and U+00E9, one name on macOS file systems and
-- two on Linux, are one page id. Limit (OQ-140): only the pairs of `COMPOSITIONS` (Latin-1 Supplement,
-- Latin Extended-A and -B in part, Latin Extended Additional, from UnicodeData 16) are composed; Greek,
-- Cyrillic, Hangul and the canonical reordering of several marks are not, and no third-party library is used.
