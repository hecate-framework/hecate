-- Generates the C source that embeds the Lua modules of the `hecate` executable. Standard library only.
local util = require("lib.util")

local M = {}

--- Packages whose sources are embedded in the executable (ADR 0029).
M.PACKAGES = { "cli", "core", "reactor", "log", "json", "schema" }

--- Module name of a source file relative to its `src` directory: `hecate/cli/main.lua` is `hecate.cli.main`
--- (`init.lua` files are also served under their directory's name, see `collect`).
---@param relative string
---@return string
function M.module_name(relative)
  local name = relative:gsub("\\", "/"):gsub("%.lua$", "")
  return (name:gsub("/", "."))
end

--- Renders bytes as the body of a C array initialiser, sixteen per line.
---@param data string
---@return string
function M.c_bytes(data)
  local parts = {}
  for i = 1, #data, 16 do
    local row = {}
    for j = i, math.min(i + 15, #data) do row[#row + 1] = ("%d"):format(data:byte(j)) end
    parts[#parts + 1] = "  " .. table.concat(row, ",") .. ","
  end
  return table.concat(parts, "\n")
end

--- Renders a C string literal (names only: ASCII module names).
---@param s string
---@return string
function M.c_string(s) return '"' .. s:gsub('[\\"]', "\\%0") .. '"' end

--- Renders the C file for a list of `{ name, source }` modules.
---@param modules {name: string, source: string}[]
---@return string
function M.render(modules)
  table.sort(modules, function(a, b) return a.name < b.name end)
  for i = 2, #modules do
    assert(modules[i - 1].name ~= modules[i].name, "cli_bundle: duplicate module " .. modules[i].name)
  end
  local out = { "/* Generated by `lua tools/run.lua build-cli`. Do not edit. */", '#include "bundle.h"', "" }
  for i, m in ipairs(modules) do
    out[#out + 1] = ("static const unsigned char module_%d[] = {\n%s\n  0\n};"):format(i, M.c_bytes(m.source))
  end
  out[#out + 1] = "\nconst hecate_module hecate_modules[] = {"
  for i, m in ipairs(modules) do
    out[#out + 1] = ("  { %s, (const char *)module_%d, %d },"):format(M.c_string(m.name), i, #m.source)
  end
  out[#out + 1] = "  { 0, 0, 0 }\n};\n"
  return table.concat(out, "\n")
end

--- Collects the modules of the embedded packages.
---@param root string   repository root
---@return {name: string, source: string}[]
function M.collect(root)
  local modules = {}
  for _, package in ipairs(M.PACKAGES) do
    local src = ("%s/packages/%s/src"):format(root, package)
    for _, path in ipairs(util.walk(src, ".lua")) do
      local f = assert(io.open(path, "rb"))
      local source = f:read("a")
      f:close()
      modules[#modules + 1] = { name = M.module_name(path:sub(#src + 2)), source = source }
    end
  end
  -- `hecate.cli.init` is also `hecate.cli`, unless a file `hecate/cli.lua` exists (as in Lua's own searcher).
  local seen = {}
  for _, m in ipairs(modules) do seen[m.name] = true end
  for _, m in ipairs({ table.unpack(modules) }) do
    local package = m.name:match("^(.+)%.init$")
    if package and not seen[package] then
      seen[package] = true
      modules[#modules + 1] = { name = package, source = m.source }
    end
  end
  return modules
end

--- The modules of a LuaRocks source tree (`src/luarocks/**.lua`) and its launcher, served as `luarocks.main`: the
--- program of `src/bin/luarocks` without its shebang line, run by `hecate --luarocks` (ADR 0029).
---@param directory string   a checkout of LuaRocks
---@return {name: string, source: string}[]
function M.collect_luarocks(directory)
  local modules = {}
  local src = directory .. "/src"
  for _, path in ipairs(util.walk(src .. "/luarocks", ".lua")) do
    local f = assert(io.open(path, "rb"))
    modules[#modules + 1] = { name = M.module_name(path:sub(#src + 2)), source = f:read("a") }
    f:close()
  end
  local f = assert(io.open(src .. "/bin/luarocks", "rb"))
  local launcher = f:read("a"):gsub("^#![^\n]*\n", "-- launcher\n")
  f:close()
  modules[#modules + 1] = { name = "luarocks.main", source = launcher }
  return modules
end

return M
