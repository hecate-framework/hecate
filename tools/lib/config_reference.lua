-- The framework keys of every configuration: the model and the Markdown page of `gen-config-reference`.
--
-- Sources, all read as files (tools never require Hecate packages):
-- - `packages/config/src/hecate/config/declaration.lua` is loaded as a chunk with stand-ins for `hecate.schema` and
--   `hecate.core` (no package is loaded): `framework_properties()` then returns a tree of plain descriptions of the
--   schema calls, and `variable_name` is the function `config` itself uses to derive environment variable names.
-- - `packages/config/src/hecate/config/load.lua` gives the default prefix (`options.env_prefix or "HECATE"`).
-- - `docs/architecture/configuration.md` gives the meaning of each key: the tables with the header
--   `| Key | Type | Default | Meaning |`. A declared key without a row, or a row for a key that is not declared, is a
--   problem: the specification and the code must agree.
local M = {}

M.MARKER = "<!-- Generated by lua tools/run.lua gen-config-reference from packages/config/src/hecate/config/declaration.lua "
  .. "and the key tables of docs/architecture/configuration.md. Do not edit: change them and generate again. -->"

--- Whether a page carries the marker of this generator (a page without it is never overwritten).
---@param content string
---@return boolean
function M.is_generated(content)
  return content:find("Generated by lua tools/run.lua gen-config-reference", 1, true) ~= nil
end

-- Loading the declaration ------------------------------------------------------------------------

local WRAPPERS = { default = true, optional = true, nullable = true, named = true }

-- A stand-in for `hecate.schema`: every constructor returns a plain description of its call.
local function schema_stub()
  local constructors = {
    default = function(item, value) return { kind = "default", item = item, value = value } end,
    optional = function(item) return { kind = "optional", item = item } end,
    nullable = function(item) return { kind = "nullable", item = item } end,
    named = function(_, item) return { kind = "named", item = item } end,
    object = function(properties) return { kind = "object", properties = properties } end,
    map = function(item, options) return { kind = "map", item = item, options = options } end,
    array = function(item, options) return { kind = "array", item = item, options = options } end,
    enumeration = function(values) return { kind = "enumeration", values = values } end,
    is_schema = function(value) return type(value) == "table" and value.kind ~= nil end,
  }
  return setmetatable({}, {
    __index = function(_, name)
      return constructors[name] or function(options) return { kind = name, options = options } end
    end,
  })
end

-- A stand-in for `hecate.core`: error classes and functions that are never called while describing.
local function core_stub()
  return setmetatable({}, { __index = function() return function(...) return ... end end })
end

--- Loads the declaration module from its source text, without loading any package.
---@param text string  source of declaration.lua
---@param chunkname? string
---@return table? module, string? error
function M.load_declaration(text, chunkname)
  local stubs = { ["hecate.schema"] = schema_stub(), ["hecate.core"] = core_stub() }
  local env = setmetatable({
    require = function(name)
      local stub = stubs[name]
      if not stub then error("declaration.lua requires " .. tostring(name) .. ", which gen-config-reference does not stand in for", 2) end
      return stub
    end,
  }, { __index = _G })
  local chunk, err = load(text, "=" .. (chunkname or "declaration.lua"), "t", env)
  if not chunk then return nil, err end
  local ok, module = pcall(chunk)
  if not ok then return nil, tostring(module) end
  if type(module) ~= "table" or type(module.framework_properties) ~= "function" or type(module.variable_name) ~= "function" then
    return nil, "declaration.lua does not return framework_properties and variable_name"
  end
  return module
end

--- The default prefix of environment variables, from the source of load.lua.
---@param text string
---@return string?
function M.default_prefix(text)
  return text:match('env_prefix%s+or%s+"([%u%d_]+)"')
end

-- Describing the keys --------------------------------------------------------------------------

local function lua_literal(value)
  local t = type(value)
  if t == "string" then return ("%q"):format(value) end
  if t == "table" then
    if next(value) == nil then return "{}" end
    local parts = {}
    for i, item in ipairs(value) do parts[i] = lua_literal(item) end
    return "{ " .. table.concat(parts, ", ") .. " }"
  end
  return tostring(value)
end

local function code_list(values)
  local parts = {}
  for i, value in ipairs(values) do parts[i] = "`" .. tostring(value) .. "`" end
  return table.concat(parts, ", ")
end

local function bounds(options)
  if type(options) ~= "table" then return {} end
  local out = {}
  local min, max = options.minimum, options.maximum
  if min ~= nil and max ~= nil then out[#out + 1] = ("%s to %s"):format(min, max)
  elseif min ~= nil then out[#out + 1] = ("at least %s"):format(min)
  elseif max ~= nil then out[#out + 1] = ("at most %s"):format(max) end
  if options.exclusive_minimum ~= nil then out[#out + 1] = ("above %s"):format(options.exclusive_minimum) end
  if options.exclusive_maximum ~= nil then out[#out + 1] = ("below %s"):format(options.exclusive_maximum) end
  local lmin, lmax = options.min_length, options.max_length
  if lmin ~= nil and lmax ~= nil then out[#out + 1] = ("length %s to %s"):format(lmin, lmax)
  elseif lmin ~= nil then out[#out + 1] = ("length at least %s"):format(lmin)
  elseif lmax ~= nil then out[#out + 1] = ("length at most %s"):format(lmax) end
  local imin, imax = options.min_items, options.max_items
  if imin ~= nil then out[#out + 1] = ("at least %s items"):format(imin) end
  if imax ~= nil then out[#out + 1] = ("at most %s items"):format(imax) end
  if options.pattern ~= nil then out[#out + 1] = ("matches `%s`"):format(options.pattern) end
  if options.format ~= nil then out[#out + 1] = ("format `%s`"):format(options.format) end
  return out
end

local function unwrap(node)
  local default, has_default, optional = nil, false, false
  while WRAPPERS[node.kind] and node.item ~= nil do
    if node.kind == "default" and not has_default then default, has_default = node.value, true end
    if node.kind == "optional" or node.kind == "nullable" then optional = true end
    node = node.item
  end
  return node, has_default, default, optional
end

-- The type and the allowed values or range of an unwrapped node.
local function describe(node)
  if node.kind == "enumeration" then
    return "enumeration", { "one of " .. code_list(node.values) }
  elseif node.kind == "array" or node.kind == "map" then
    local item = unwrap(node.item)
    local item_type, item_allowed = describe(item)
    local allowed = {}
    local label = node.kind == "array" and "items: " or "values: "
    for _, a in ipairs(item_allowed) do allowed[#allowed + 1] = label .. a end
    for _, b in ipairs(bounds(node.options)) do allowed[#allowed + 1] = b end
    local word = node.kind == "array" and "array of " or "map of string to "
    return word .. item_type, allowed
  end
  return node.kind, bounds(node.options)
end

--- The declared keys, sorted by path: maps and leaves (an object is walked, not listed).
---@param properties table<string, table>  framework_properties() under the stand-ins
---@param variable_name fun(prefix: string, segments: string[]): string
---@param prefix string
---@return table[] keys
function M.keys(properties, variable_name, prefix)
  local keys = {}
  local function visit(node, segments, inherited_optional)
    local inner, has_default, default, optional = unwrap(node)
    optional = optional or inherited_optional
    if inner.kind == "object" then
      local names = {}
      for name in pairs(inner.properties) do names[#names + 1] = name end
      table.sort(names)
      for _, name in ipairs(names) do
        local path = { table.unpack(segments) }
        path[#path + 1] = name
        -- A property of an optional object without a default is absent with it.
        visit(inner.properties[name], path, optional and not has_default)
      end
      return
    end
    local type_text, allowed = describe(inner)
    local key = {
      key = table.concat(segments, "."),
      type = type_text,
      allowed = allowed,
      default = has_default and lua_literal(default) or nil,
      optional = optional and not has_default,
    }
    if inner.kind == "map" or (inner.kind == "array" and unwrap(inner.item).kind == "object") then
      key.files_only = true
    else
      key.variable = variable_name(prefix, segments)
      key.list = inner.kind == "array"
    end
    keys[#keys + 1] = key
  end
  local names = {}
  for name in pairs(properties) do names[#names + 1] = name end
  table.sort(names)
  for _, name in ipairs(names) do visit(properties[name], { name }, false) end
  return keys
end

-- The specification ----------------------------------------------------------------------------

-- Splits a table row at the pipes outside inline code (`\|` is a literal pipe).
local function split_row(line)
  local cells, current, code = {}, {}, false
  local i = 1
  while i <= #line do
    local c = line:sub(i, i)
    if c == "\\" and line:sub(i + 1, i + 1) == "|" then
      current[#current + 1] = "\\|"
      i = i + 1
    elseif c == "`" then
      code = not code
      current[#current + 1] = c
    elseif c == "|" and not code then
      cells[#cells + 1] = table.concat(current):match("^%s*(.-)%s*$")
      current = {}
    else
      current[#current + 1] = c
    end
    i = i + 1
  end
  cells[#cells + 1] = table.concat(current):match("^%s*(.-)%s*$")
  -- A row starts and ends with a pipe: drop the empty first and last cells.
  if cells[1] == "" then table.remove(cells, 1) end
  if cells[#cells] == "" then cells[#cells] = nil end
  return cells
end

-- Relative links of the specification do not resolve on the website: keep their text.
local function strip_relative_links(text)
  return (text:gsub("%[([^%]]*)%]%(([^)]*)%)", function(label, target)
    if target:find("^https?://") then return nil end
    return label
  end))
end

--- The meaning of each key, from the `| Key | Type | Default | Meaning |` tables of a specification.
---@param text string
---@return table<string, { meaning: string, line: integer }>
function M.meanings(text)
  local out, in_table, line_number = {}, false, 0
  for line in (text .. "\n"):gmatch("([^\n]*)\n") do
    line_number = line_number + 1
    if line:find("^|%s*Key%s*|%s*Type%s*|%s*Default%s*|%s*Meaning%s*|%s*$") then
      in_table = true
    elseif in_table and line:find("^|") then
      local cells = split_row(line)
      local key = cells[1] and cells[1]:match("^`([%w_.]+)`$")
      if key and cells[4] then out[key] = { meaning = strip_relative_links(cells[4]), line = line_number } end
    else
      in_table = false
    end
  end
  return out
end

-- Model and page -------------------------------------------------------------------------------

--- Builds the model from the three source texts.
---@param sources { declaration: string, load: string, specification: string }
---@return { keys: table[], prefix: string?, problems: string[] }
function M.build(sources)
  local problems = {}
  local module, err = M.load_declaration(sources.declaration)
  if not module then return { keys = {}, problems = { "declaration.lua: " .. tostring(err) } } end
  local prefix = M.default_prefix(sources.load)
  if not prefix then
    problems[#problems + 1] = 'load.lua: the default prefix (`env_prefix or "..."`) was not found'
    prefix = "HECATE"
  end
  local ok, properties = pcall(module.framework_properties)
  if not ok then return { keys = {}, prefix = prefix, problems = { "framework_properties: " .. tostring(properties) } } end
  local keys = M.keys(properties, module.variable_name, prefix)
  local meanings = M.meanings(sources.specification)
  local declared = {}
  for _, key in ipairs(keys) do
    declared[key.key] = true
    local entry = meanings[key.key]
    if entry then key.description = entry.meaning
    else
      problems[#problems + 1] = ("configuration.md: the declared key %s has no row in a `| Key | Type | Default | Meaning |` table"):format(key.key)
    end
  end
  local stale = {}
  for name, entry in pairs(meanings) do
    if not declared[name] then stale[#stale + 1] = ("configuration.md:%d: %s is not a declared framework key"):format(entry.line, name) end
  end
  table.sort(stale)
  for _, p in ipairs(stale) do problems[#problems + 1] = p end
  return { keys = keys, prefix = prefix, problems = problems }
end

local function cell(s) return (s:gsub("([^\\])|", "%1\\|")) end

--- Renders the page.
---@param model { keys: table[], prefix?: string }
---@return string
function M.render(model)
  local out = {
    "---",
    "title: Configuration keys",
    'description: "The keys that every hecate configuration declares: type, default, allowed values, environment variable and meaning."',
    'hecate: "0.x"',
    'lua: "5.5"',
    "order: 1010",
    "generated: true",
    'source: "packages/config/src/hecate/config/declaration.lua"',
    "---",
    "",
    M.MARKER,
    "",
    "# Configuration keys",
    "",
    "Every configuration declares these keys besides the properties of the application, whose names cannot reuse",
    "the first segment of a framework key. Each key is read from the files, then from its environment variable;",
    ("the variable names use the default prefix `%s` (the `env_prefix` option of `config.load` replaces it)."):format(
      model.prefix or "HECATE"),
    "A list is written in a variable with its items separated by commas. A map is configured by files only.",
    "",
    "| Key | Type | Default | Allowed | Environment variable | Description |",
    "|---|---|---|---|---|---|",
  }
  for _, key in ipairs(model.keys) do
    local default = key.default and ("`" .. key.default .. "`") or (key.optional and "none (optional)" or "none (required)")
    local allowed = #key.allowed > 0 and table.concat(key.allowed, "; ") or "any"
    local variable = key.files_only and "none (files only)"
      or ("`%s`%s"):format(key.variable, key.list and " (comma separated)" or "")
    out[#out + 1] = ("| `%s` | %s | %s | %s | %s | %s |"):format(key.key, cell(key.type), cell(default), cell(allowed),
      variable, cell(key.description or ""))
  end
  return table.concat(out, "\n") .. "\n"
end

return M
