-- The architecture specifications and the ADRs as pages of the maintainer site (OQ-144, owner decision of 2026-11-21).
-- The files of `docs/architecture/` and `docs/adr/` stay the source of truth: `gen-maintainer-docs` writes a page for
-- each into `website/maintainer/en/` (git-ignored, marked as generated), with the front matter a page needs and the
-- links rewritten. This module holds the pure functions; tools never require Hecate packages.
local M = {}

M.OUT_DIR = "website/maintainer/en"
M.REPOSITORY_URL = "https://github.com/hecate-framework/hecate/blob/main/"
M.MARKER = "<!-- Generated by lua tools/run.lua gen-maintainer-docs from %s. Do not edit: change the source file. -->"

--- Whether a file is a generated page (carries the marker).
---@param content string
---@return boolean
function M.is_generated(content)
  return content:find("Generated by lua tools/run.lua gen-maintainer-docs", 1, true) ~= nil
end

--- The page that a source file becomes: `docs/architecture/x.md`, `docs/adr/x.md` and `docs/reviews/x.md` keep their name
--- under `architecture/`, `adr/` and `reviews/`, `docs/roadmap.md` and `docs/open-questions.md` are pages of the root of
--- the site, and `docs/adr/README.md` is the index of `adr/`.
---@param source string  repository-relative path
---@return string  repository-relative path of the page
function M.target(source)
  local directory, name = source:match("^docs/(%a+)/([^/]+)$")
  if name == "README.md" then name = "index.md" end
  if directory then return ("%s/%s/%s"):format(M.OUT_DIR, directory, name) end
  return ("%s/%s"):format(M.OUT_DIR, source:match("^docs/([^/]+)$"))
end

--- Whether a repository path is published as a page of the maintainer site (and so linked relatively).
---@param path string  normalised repository path
---@return boolean
function M.is_published(path)
  return path:find("^docs/architecture/[^/]+%.md$") ~= nil or path:find("^docs/adr/[^/]+%.md$") ~= nil
    or path:find("^docs/reviews/[^/]+%.md$") ~= nil or path == "docs/roadmap.md" or path == "docs/open-questions.md"
end

--- Normalises `a/b/../c` (no leading `..` allowed to escape: the result may start with `..`).
local function normalise(path)
  local parts = {}
  for segment in path:gmatch("[^/]+") do
    if segment == ".." then
      if #parts > 0 and parts[#parts] ~= ".." then parts[#parts] = nil else parts[#parts + 1] = ".." end
    elseif segment ~= "." then
      parts[#parts + 1] = segment
    end
  end
  return table.concat(parts, "/")
end

--- The relative path from a page to another one (both repository paths of generated pages).
local function relative(from, to)
  local from_parts, to_parts = {}, {}
  for segment in from:gmatch("[^/]+") do from_parts[#from_parts + 1] = segment end
  for segment in to:gmatch("[^/]+") do to_parts[#to_parts + 1] = segment end
  local common = 0
  while common < #from_parts - 1 and common < #to_parts - 1 and from_parts[common + 1] == to_parts[common + 1] do
    common = common + 1
  end
  local out = {}
  for _ = common + 1, #from_parts - 1 do out[#out + 1] = ".." end
  for i = common + 1, #to_parts do out[#out + 1] = to_parts[i] end
  return table.concat(out, "/")
end

local function rewrite_target(source, target)
  if target:find("^%a[%w+.-]*:") or target:find("^#") or target:find("^/") then return target end
  local path, fragment = target:match("^([^#]*)(#?.*)$")
  local directory = source:match("^(.*)/[^/]*$") or "."
  local resolved = normalise(directory .. "/" .. path)
  -- A link that leaves the repository is left as written (it would only be broken on GitHub).
  if resolved:find("^%.%.") then return target end
  if M.is_published(resolved) then
    return relative(M.target(source), M.target(resolved)) .. fragment
  end
  if resolved == "docs/glossary.md" then
    -- A page is served at `<directory>/<name>/`, the index of a directory at `<directory>/`: one level less.
    local from, name = M.target(source):match("^website/maintainer/en/(.-)([^/]*)$")
    local _, depth = (from or ""):gsub("[^/]+", "")
    if name ~= "index.md" then depth = depth + 1 end
    return ("../"):rep(depth + 2) .. "user/en/reference/glossary/" .. fragment
  end
  return M.REPOSITORY_URL .. resolved .. fragment
end

-- The text outside code spans: inline links (with an optional title) are rewritten. A code span is a run of backticks up to
-- the next run of the same length (CommonMark), kept as written.
local function rewrite_text(source, text)
  return (text:gsub("%]%(([^)%s]+)([^)]*)%)", function(target, rest)
    return "](" .. rewrite_target(source, target) .. rest .. ")"
  end))
end

local function rewrite_line(source, line)
  local out, position = {}, 1
  while position <= #line do
    local open_start, open_end = line:find("`+", position)
    local close_start, close_end
    if open_start then
      local length = open_end - open_start + 1
      local from = open_end + 1
      while true do
        close_start, close_end = line:find("`+", from)
        if not close_start or close_end - close_start + 1 == length then break end
        from = close_end + 1
      end
    end
    if not open_start or not close_start then
      out[#out + 1] = rewrite_text(source, line:sub(position))
      break
    end
    out[#out + 1] = rewrite_text(source, line:sub(position, open_start - 1))
    out[#out + 1] = line:sub(open_start, close_end)
    position = close_end + 1
  end
  local text = table.concat(out)
  -- Reference-style definitions: `[label]: target "title"`.
  return (text:gsub("^(%s*%[[^%]]+%]:%s*)(%S+)", function(head, target) return head .. rewrite_target(source, target) end))
end

--- The title (first `# ` heading) and the description (the first paragraph of prose, on one line, or a standard text).
---@param text string
---@return string title, string description
function M.describe(text)
  text = text:gsub("\r\n", "\n")
  local title = text:match("^# ([^\n]+)") or text:match("\n# ([^\n]+)") or "Untitled"
  local after = text:match("\n# [^\n]*\n(.*)$") or text:match("^# [^\n]*\n(.*)$") or ""
  local description
  for paragraph in (after .. "\n\n"):gmatch("(.-)\n%s*\n") do
    local first = paragraph:match("^%s*(.)")
    if first and not first:find("[-*|#>`<%d]") then
      description = paragraph:gsub("%s*\n%s*", " "):gsub("%[([^%]]*)%]%([^)]*%)", "%1"):gsub("[`*_]", ""):match("^%s*(.-)%s*$")
      break
    end
  end
  if description and #description > 240 then description = description:sub(1, 237):gsub("%s+%S*$", "") .. "..." end
  return title, description or ("Architecture decision record: " .. title)
end

--- The page for a source file.
---@param source string  repository-relative path of the source
---@param text string  its content
---@return string
function M.render(source, text)
  text = text:gsub("\r\n", "\n")
  local title, description = M.describe(text)
  if source:find("^docs/architecture/") then
    description = description:gsub("^Architecture decision record: ", "Architecture specification: ")
  end
  local lines, fence_character, fence_length = {}, nil, 0
  for line in (text .. "\n"):gmatch("(.-)\n") do
    local marks = line:match("^%s*(```+)") or line:match("^%s*(~~~+)")
    local kept = false
    if marks then
      if not fence_character then
        fence_character, fence_length, kept = marks:sub(1, 1), #marks, true
      elseif marks:sub(1, 1) == fence_character and #marks >= fence_length and line:match("^%s*[`~]+%s*$") then
        fence_character, fence_length, kept = nil, 0, true
      end
    end
    lines[#lines + 1] = (fence_character or kept) and line or rewrite_line(source, line)
  end
  while lines[#lines] == "" do lines[#lines] = nil end
  local function quoted(value) return '"' .. value:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"' end
  local front = ('---\ndescription: %s\nhecate: "0.x"\nlua: "5.5"\nsource: %s\ngenerated: true\n---\n\n'):format(
    quoted(description), quoted(source))
  local body = table.concat(lines, "\n")
  -- The marker goes after the first heading, like the other generated pages.
  local head, rest = body:match("^(# [^\n]*\n)(.*)$")
  if not head then head, rest = "", body end
  return front .. head .. "\n" .. M.MARKER:format(source) .. "\n" .. rest .. "\n"
end

return M
