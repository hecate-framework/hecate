-- The error classes of the packages, read from their source files (never loaded): the model and the
-- Markdown page of `gen-error-codes` (ADR 0018: every error class and code is documented).
--
-- A class is found from its declaration and its LuaLS annotation block (the `---` lines right above it):
--   local X = core.error_class("Name", "code"[, Parent])      -- also `errors.X = error_class(...)`
--   local X = class_module.class("Name"[, Parent]) ... X.code = "code"
--   local X = declare("Name", Parent)   -- a local `declare(name, ...)` whose body sets `class.code = "<prefix>" .. name`
--                                        -- (the kernel); `.. "." .. reason` in that body refines the code per reason
-- and, for classes created in a loop, from the fields of a module class typed as a declared error class
-- in the file of that class (`---@field NotFound hecate.kernel.problem.ProblemDetails  404`): code = namespace of the
-- base code + field name.
--
-- `context.reason` values, in order of preference: the literal union of the `reason` member of `---@field context`,
-- the `---@alias` that member names, else the description (the sentence that introduces `context.reason`, or the
-- bullet list it announces with a colon).
local M = {}

M.MARKER = "<!-- Generated by lua tools/run.lua gen-error-codes from the error classes of packages/*/src. "
  .. "Do not edit: change the annotations of the error classes and generate again. -->"

--- Whether a page carries the marker of this generator (a page without it is never overwritten).
---@param content string
---@return boolean
function M.is_generated(content)
  return content:find("Generated by lua tools/run.lua gen-error-codes", 1, true) ~= nil
end

-- Doc blocks ---------------------------------------------------------------------------------

-- The text of a doc block: description lines (before the first tag) and the tags.
local function parse_block(block)
  local description, tags, in_tags = {}, {}, false
  for _, line in ipairs(block) do
    if line:find("^@") then
      in_tags = true
      tags[#tags + 1] = line
    elseif not in_tags then
      description[#description + 1] = line
    end
  end
  while description[#description] == "" do description[#description] = nil end
  return description, tags
end

-- Paragraphs of description lines: { lines = {...}, bullets = bool }.
local function paragraphs(lines)
  local out, current = {}, nil
  for _, line in ipairs(lines) do
    if line == "" then
      current = nil
    else
      if not current then
        current = { lines = {}, bullets = line:find("^%- ") ~= nil }
        out[#out + 1] = current
      end
      current.lines[#current.lines + 1] = line
    end
  end
  return out
end

local function join(lines)
  local parts = {}
  for i, line in ipairs(lines) do parts[i] = (line:gsub("^%s+", "")) end
  return table.concat(parts, " ")
end

-- The first sentence of a text: up to the first ". " (or final ".") outside backticks and parentheses.
local function first_sentence(text)
  local depth, code = 0, false
  for i = 1, #text do
    local c = text:sub(i, i)
    if c == "`" then code = not code
    elseif not code then
      if c == "(" then depth = depth + 1
      elseif c == ")" then depth = math.max(0, depth - 1)
      elseif c == "." and depth == 0 and (i == #text or text:sub(i + 1, i + 1) == " ") then
        return text:sub(1, i)
      end
    end
  end
  return text
end

-- Reason extraction from prose ---------------------------------------------------------------

local function is_reason_token(token) return token:find("^[a-z][a-z0-9_]*$") ~= nil end

-- Scans `text` from `start`: returns the backticked tokens at depth 0 and at depth 1 (parentheses), stopping at
-- the end of the sentence, a `;`, or another `context.<member>` at depth 0. With `stop_at_colon`, also stops at
-- the first `:` at depth 0 (the head of a bullet item).
local function scan_tokens(text, start, stop_at_colon)
  local depth0, depth1 = {}, {}
  local depth, i = 0, start
  while i <= #text do
    local c = text:sub(i, i)
    if c == "`" then
      local close = text:find("`", i + 1, true)
      if not close then break end
      local token = text:sub(i + 1, close - 1)
      if depth == 0 and token:find("^context%.") and token ~= "context.reason" then break end
      if is_reason_token(token) then
        if depth == 0 then depth0[#depth0 + 1] = token elseif depth == 1 then depth1[#depth1 + 1] = token end
      end
      i = close
    elseif c == "(" then depth = depth + 1
    elseif c == ")" then depth = math.max(0, depth - 1)
    elseif depth == 0 and (c == ";" or (c == "." and (i == #text or text:sub(i + 1, i + 1) == " "))
        or (stop_at_colon and c == ":")) then
      break
    end
    i = i + 1
  end
  return depth0, depth1
end

local function unique(list)
  local seen, out = {}, {}
  for _, v in ipairs(list) do
    if not seen[v] then seen[v] = true out[#out + 1] = v end
  end
  return out
end

-- Bullet items of a paragraph, continuation lines joined.
local function items(paragraph)
  local out = {}
  for _, line in ipairs(paragraph.lines) do
    if line:find("^%- ") then out[#out + 1] = line:sub(3)
    elseif #out > 0 then out[#out] = out[#out] .. " " .. line:gsub("^%s+", "") end
  end
  return out
end

--- The `context.reason` values a description lists, or nil when it does not mention `context.reason`.
---@param description string[]  description lines of a doc block
---@return string[]?
function M.reasons_from_description(description)
  local paras = paragraphs(description)
  for index, paragraph in ipairs(paras) do
    local text = join(paragraph.lines)
    local _, at = text:find("`context.reason`", 1, true)
    if at then
      local announced = text:find(":%s*$") ~= nil
      local next_paragraph = paras[index + 1]
      if announced and next_paragraph and next_paragraph.bullets then
        local found = {}
        for _, item in ipairs(items(next_paragraph)) do
          local depth0 = scan_tokens(item, 1, true)
          for _, token in ipairs(depth0) do found[#found + 1] = token end
        end
        return unique(found)
      end
      local depth0, depth1 = scan_tokens(text, at + 1, false)
      return unique(#depth0 > 0 and depth0 or depth1)
    end
  end
  return nil
end

-- Annotations --------------------------------------------------------------------------------

-- The type of the `reason` member of a `---@field context { ... }` table type, or nil.
local function reason_type(context_type)
  if not context_type then return nil end
  local inner = context_type:match("^{(.*)}$")
  if not inner then return nil end
  local t = inner:match("[{,]?%s*reason%??%s*:%s*([^,}]+)")
  return t and (t:gsub("%s+$", "")) or nil
end

-- The literal strings of a union type (`"a"|"b"`), or nil when the type is not such a union.
local function literal_union(t)
  local values = {}
  for part in (t .. "|"):gmatch("([^|]*)|") do
    local v = part:match('^%s*"([^"]*)"%s*$')
    if not v then return nil end
    values[#values + 1] = { name = v }
  end
  return #values > 0 and values or nil
end

--- The `---@alias` declarations of a source: name -> list of { name, description? } (literal members only).
---@param text string
---@param aliases table<string, table[]>  filled in place
function M.collect_aliases(text, aliases)
  local current
  for line in (text .. "\n"):gmatch("([^\n]*)\n") do
    local name, rest = line:match("^%s*%-%-%-@alias%s+([%w_.]+)%s*(.*)$")
    if name then
      current = nil
      local members = rest ~= "" and literal_union(rest) or nil
      if members then aliases[name] = members
      elseif rest == "" then current = {} aliases[name] = current end
    elseif current then
      local value, description = line:match('^%s*%-%-%-|%s*"([^"]*)"%s*(.*)$')
      if value then
        current[#current + 1] = { name = value, description = description ~= "" and description or nil }
      else
        current = nil
      end
    end
  end
end

-- Declarations -------------------------------------------------------------------------------

local function balance(s)
  local n = 0
  for c in s:gmatch("[()]") do n = n + (c == "(" and 1 or -1) end
  return n
end

-- `local f = require("hecate.<package>")` -> f = package.
local function requires_of(text)
  local map = {}
  for name, package_name in text:gmatch('local%s+([%w_]+)%s*=%s*require%(%s*"hecate%.([%w_]+)"%s*%)') do
    map[name] = package_name
  end
  return map
end

-- Local functions that declare error classes: name -> { prefix, refined }.
local function declarers_of(text)
  local map = {}
  for name, param, body in text:gmatch("\nlocal function ([%w_]+)%(([%w_]+)[^)]*%)(.-)\nend") do
    local prefix = body:match('%.code%s*=%s*"([^"]+)"%s*%.%.%s*' .. param .. "%f[^%w_]")
    if prefix then
      map[name] = { prefix = prefix, refined = body:find('%.%.%s*"%."%s*%.%.%s*reason') ~= nil }
    end
  end
  return map
end

--- Scans one source file. Returns the declarations found, unresolved (parent is an expression).
---@param path string  repository-relative path (`packages/<package>/src/...`)
---@param text string
---@return table[] declarations, table[] module_fields
function M.scan(path, text)
  local package_name = path:match("^packages/([^/]+)/src/")
  local requires, declarers = requires_of(text), declarers_of("\n" .. text)
  local lines = {}
  for line in (text .. "\n"):gmatch("([^\n]*)\n") do lines[#lines + 1] = line end
  local found, pending, fields = {}, {}, {}
  local block = {}
  local i = 1
  while i <= #lines do
    local line = lines[i]
    local doc = line:match("^%s*%-%-%-(.*)$")
    if doc then
      block[#block + 1] = (doc:gsub("^ ", ""))
      i = i + 1
    else
      local statement, first = line, i
      while balance(statement) > 0 and i < #lines do
        i = i + 1
        statement = statement .. " " .. lines[i]:gsub("^%s+", "")
      end
      statement = statement:gsub("^%s+", "")
      local lhs, rhs = statement:match("^local%s+([%w_]+)%s*=%s*(.+)$")
      if not lhs then lhs, rhs = statement:match("^[%w_]+%.([%w_]+)%s*=%s*(.+)$") end
      local description, tags = parse_block(block)
      local entry
      if rhs then
        local name, code, rest = rhs:match('error_class%(%s*"([%w_]+)"%s*,%s*"([^"]+)"%s*(.-)%)')
        if name then
          entry = { name = name, code = code, parent_expr = rest:match("^,%s*([%w_.]+)") or "core.Error" }
        else
          local call, cname, crest = rhs:match('^([%w_.]+)%(%s*"([%w_]+)"%s*(.-)%)')
          if call and (call == "class" or call:find("%.class$")) then
            pending[lhs] = { name = cname, parent_expr = crest:match("^,%s*([%w_.]+)"), lhs = lhs }
            entry = pending[lhs]
            entry.pending = true
          elseif call and declarers[call] then
            local d = declarers[call]
            entry = { name = cname, code = d.prefix .. cname, refined = d.refined,
              parent_expr = crest:match("^,%s*([%w_.]+)") or "core.Error" }
          end
        end
      end
      local owner, code = statement:match('^([%w_]+)%.code%s*=%s*"([^"]+)"')
      if owner and pending[owner] and not pending[owner].code then
        pending[owner].code = code
        pending[owner].pending = nil
      end
      if entry then
        entry.package = package_name
        entry.file = path
        entry.line = first
        entry.local_name = lhs
        entry.requires = requires
        entry.description = description
        for _, tag in ipairs(tags) do
          local class_type = tag:match("^@class%s+([%w_.]+)")
          if class_type then entry.type = class_type end
          local context_type = tag:match("^@field%s+context%s+(%b{})")
          if context_type then entry.context = context_type end
        end
        found[#found + 1] = entry
      end
      -- Fields of a module class: candidates for classes created in a loop.
      for _, tag in ipairs(tags) do
        local fname, ftype, fdesc = tag:match("^@field%s+(%u[%w_]*)%s+([%w_.]+)%s+(.*)$")
        if not fname then
          fname, ftype = tag:match("^@field%s+(%u[%w_]*)%s+([%w_.]+)$")
          fdesc = ""
        end
        if fname then fields[#fields + 1] = { name = fname, type = ftype, description = fdesc, file = path, package = package_name } end
      end
      block = {}
      i = i + 1
    end
  end
  local declarations = {}
  for _, entry in ipairs(found) do
    if entry.code and not entry.pending then declarations[#declarations + 1] = entry end
  end
  return declarations, fields
end

-- Model --------------------------------------------------------------------------------------

local function anchor(code) return (code:lower():gsub("[^%w]+", "-")) end

--- Builds the model from the source files.
---@param files { path: string, text: string }[]  repository-relative paths below `packages/<package>/src/`
---@return { classes: table[], warnings: string[], problems: string[] }
function M.build(files)
  local aliases, declarations, fields = {}, {}, {}
  for _, file in ipairs(files) do
    M.collect_aliases(file.text, aliases)
    local d, f = M.scan(file.path, file.text)
    for _, entry in ipairs(d) do declarations[#declarations + 1] = entry end
    for _, entry in ipairs(f) do fields[#fields + 1] = entry end
  end
  local problems, warnings = {}, {}
  local by_package_name, by_code, by_type = {}, {}, {}
  for _, entry in ipairs(declarations) do
    local key = entry.package .. "." .. entry.name
    if by_code[entry.code] then
      problems[#problems + 1] = ("%s:%d: code %s is declared twice (also %s:%d)"):format(entry.file, entry.line,
        entry.code, by_code[entry.code].file, by_code[entry.code].line)
    end
    by_code[entry.code] = entry
    by_package_name[key] = by_package_name[key] or entry
    if entry.type then by_type[entry.type] = entry end
  end
  -- Parents.
  local function resolve(entry)
    local expr = entry.parent_expr
    if not expr then return nil end
    local qualifier, name = expr:match("^([%w_]+)%.([%w_]+)$")
    local package_name = entry.package
    if qualifier and entry.requires[qualifier] then package_name = entry.requires[qualifier]
    elseif not qualifier then name = expr end
    local parent = by_package_name[package_name .. "." .. (name or "")]
    if not parent then
      problems[#problems + 1] = ("%s:%d: parent %s of %s is not a declared error class"):format(entry.file,
        entry.line, expr, entry.code)
    end
    return parent
  end
  for _, entry in ipairs(declarations) do
    local parent = resolve(entry)
    entry.parent = parent and parent.code or nil
  end
  -- Classes created in a loop, documented as fields of a module class.
  for _, field in ipairs(fields) do
    local base = by_type[field.type]
    -- Only in the file of the base class: a field elsewhere re-exports a class declared under another name.
    if base and field.file == base.file and field.name ~= base.name
        and not by_package_name[field.package .. "." .. field.name] then
      local namespace = base.code:match("^(.*)%.[%w_]+$")
      local code = namespace .. "." .. field.name
      if not by_code[code] then
        local status = field.description:match("^(%d%d%d)$")
        local entry = {
          name = field.name, code = code, package = field.package, file = field.file, line = 0,
          type = base.type, parent = base.code,
          description = { status and ("The problem of status " .. status .. ".") or field.description },
          derived = true,
        }
        by_code[code] = entry
        declarations[#declarations + 1] = entry
      end
    end
  end
  -- Descriptions and reasons.
  for _, entry in ipairs(declarations) do
    local text = join(entry.description or {})
    entry.summary = text ~= "" and first_sentence(text) or nil
    if not entry.summary then
      warnings[#warnings + 1] = ("%s:%d: %s has no LuaLS annotation (no description)"):format(entry.file, entry.line, entry.code)
    end
    local t = reason_type(entry.context)
    local union = t and literal_union(t)
    if union then
      entry.reasons, entry.reasons_from = union, "annotation"
    elseif t and aliases[t] then
      entry.reasons, entry.reasons_from, entry.reasons_alias = aliases[t], "alias", t
    else
      local names = M.reasons_from_description(entry.description or {})
      if names and #names > 0 then
        local list = {}
        for i, name in ipairs(names) do list[i] = { name = name } end
        entry.reasons, entry.reasons_from = list, "description"
      elseif t or names then
        warnings[#warnings + 1] = ("%s:%d: %s documents context.reason but its values could not be extracted"):format(
          entry.file, entry.line, entry.code)
      end
    end
    entry.anchor = anchor(entry.code)
    entry.requires = nil
  end
  table.sort(declarations, function(a, b) return a.code < b.code end)
  return { classes = declarations, warnings = warnings, problems = problems }
end

-- Rendering ----------------------------------------------------------------------------------

local function cell(s) return (s:gsub("|", "\\|")) end

local SOURCES = {
  annotation = "the literal type of `context.reason` in the annotation",
  alias = "the alias `%s`",
  description = "the description of the class",
}

--- Renders the page.
---@param model { classes: table[] }
---@return string
function M.render(model)
  local out = {
    "---",
    "title: Error codes",
    'description: "Every error class of hecate: its stable code, class, package, parent and the reasons it carries."',
    'hecate: "0.x"',
    'lua: "5.5"',
    "order: 1000",
    "generated: true",
    "---",
    "",
    M.MARKER,
    "",
    "# Error codes",
    "",
    "Every failure raises an instance of an error class rooted at `hecate.core.Error`. Each class has a stable `code`;",
    "match on the code for one precise failure, and on the class (with its subclasses) for a family. Classes that carry",
    "a `context.reason` list its values below the table.",
    "",
    "## Classes",
    "",
    "| Code | Class | Package | Parent | Description |",
    "|---|---|---|---|---|",
  }
  local by_code = {}
  for _, class in ipairs(model.classes) do by_code[class.code] = class end
  for _, class in ipairs(model.classes) do
    local code = class.reasons and ("[`%s`](#%s)"):format(class.code, class.anchor) or ("`" .. class.code .. "`")
    local parent = class.parent and ("`%s`"):format(class.parent) or "none (root)"
    out[#out + 1] = ("| %s | `%s` | `hecate.%s` | %s | %s |"):format(code, cell(class.type or class.name),
      class.package, parent, cell(class.summary or "No description in the source."))
  end
  local with_reasons = {}
  for _, class in ipairs(model.classes) do
    if class.reasons then with_reasons[#with_reasons + 1] = class end
  end
  if #with_reasons > 0 then
    out[#out + 1] = ""
    out[#out + 1] = "## Reasons"
    out[#out + 1] = ""
    out[#out + 1] = "The values of `context.reason`, a stable identifier that tells the failures of one class apart."
    for _, class in ipairs(with_reasons) do
      out[#out + 1] = ""
      out[#out + 1] = ("### `%s` {#%s}"):format(class.code, class.anchor)
      out[#out + 1] = ""
      local source = SOURCES[class.reasons_from]:format(class.reasons_alias or "")
      out[#out + 1] = ("From %s."):format(source)
      if class.refined then
        out[#out + 1] = ("The code of an instance with a reason is `%s.<reason>`."):format(class.code)
      end
      if class.context then
        out[#out + 1] = ("Context: `%s`."):format(class.context)
      end
      out[#out + 1] = ""
      local described = false
      for _, reason in ipairs(class.reasons) do described = described or reason.description ~= nil end
      if described then
        out[#out + 1] = "| Reason | Description |"
        out[#out + 1] = "|---|---|"
        for _, reason in ipairs(class.reasons) do
          out[#out + 1] = ("| `%s` | %s |"):format(reason.name, cell(reason.description or ""))
        end
      else
        local names = {}
        for i, reason in ipairs(class.reasons) do names[i] = "`" .. reason.name .. "`" end
        out[#out + 1] = table.concat(names, ", ") .. "."
      end
    end
  end
  return table.concat(out, "\n") .. "\n"
end

return M
